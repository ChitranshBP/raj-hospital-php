                <h2 class="raj-h2"><i data-feather="help-circle" class="raj-h2-icon"></i> Why Does a Spinal Headache Happen?</h2>
                <p class="text-gray-700 mb-4">
                    Your brain and spinal cord float in cerebrospinal fluid (CSF), which cushions and supports the brain. During a spinal anesthetic, epidural, or lumbar puncture, a needle passes near or through the membrane (the dura) that holds this fluid. Occasionally a small hole remains and CSF slowly leaks out. With less fluid to cushion it, the brain sags slightly when you're upright — tugging on pain-sensitive structures and producing that characteristic <strong>positional headache</strong> that vanishes when you lie down.
                </p>
                <p class="text-gray-700 mb-4">
                    The headache is typically felt at the front and back of the head, may spread to the neck and shoulders, and can come with a stiff neck, nausea, sensitivity to light, or occasionally ringing in the ears. It usually starts within 1–2 days of the procedure.
                </p>

                <h2 class="raj-h2"><i data-feather="home" class="raj-h2-icon"></i> Safe Home Remedies for a Spinal Headache</h2>
                <p class="text-gray-700 mb-4">
                    These conservative measures make you more comfortable while the leak heals. They are supportive care — not a guaranteed cure — but for many people they're enough.
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="chevrons-down" class="raj-icon raj-icon-md raj-icon-secondary"></i> Lie flat and rest</h3>
                        <p class="raj-card-body">Lying flat relieves the pain and takes pressure off the leak. Rest horizontally as much as possible in the first day or two, getting up gently and only as needed.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="droplet" class="raj-icon raj-icon-md raj-icon-secondary"></i> Drink plenty of fluids</h3>
                        <p class="raj-card-body">Staying well hydrated supports healthy spinal-fluid levels. Water, oral rehydration drinks and soups are all good — keep sipping steadily through the day.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="coffee" class="raj-icon raj-icon-md raj-icon-secondary"></i> Try caffeine</h3>
                        <p class="raj-card-body">Caffeine from tea, coffee or a caffeinated drink can temporarily narrow blood vessels and reduce the headache. It's a recognised supportive measure — but don't overdo it, especially at night.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="thermometer" class="raj-icon raj-icon-md raj-icon-secondary"></i> Simple pain relief</h3>
                        <p class="raj-card-body">Paracetamol, taken as directed, can take the edge off. Check with your doctor before combining medicines, particularly if you're recovering from surgery or childbirth.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="moon" class="raj-icon raj-icon-md raj-icon-secondary"></i> Reduce strain</h3>
                        <p class="raj-card-body">Avoid heavy lifting and hard straining while you recover. Support your neck comfortably and keep a calm, quiet, low-light environment.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="phone" class="raj-icon raj-icon-md raj-icon-secondary"></i> Keep in touch with your doctor</h3>
                        <p class="raj-card-body">Tell the anesthetist or doctor who did your procedure. They can track your progress and arrange definitive treatment quickly if home care isn't working.</p>
                    </div>
                </div>

                <div class="raj-callout raj-callout-danger">
                    <i data-feather="alert-octagon" class="raj-callout-icon"></i>
                    <div class="raj-callout-body">
                        <strong>Seek urgent medical care if your spinal headache comes with:</strong> fever or a stiff neck, seizures, changes in vision or hearing, weakness, numbness, slurred speech or confusion — or if the headache <em>no longer improves when you lie flat</em>. These can signal a serious complication and need immediate evaluation at the <a href="https://rajhospitals.com/contact.php" class="text-secondary-600 hover:underline font-semibold">RAJ Hospital emergency department</a>, not home treatment.
