                <h2 class="raj-h2"><i data-feather="message-circle" class="raj-h2-icon"></i> Frequently Asked Questions</h2>
                <div class="space-y-4">
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">How do I do a breast self-exam correctly?</h3>
                        <p class="text-gray-700">Use three steps. Look in a mirror with arms down, then raised, then hands pressed on hips, checking for shape change, dimpling or nipple change. Then feel while lying down with a pillow under the shoulder, using the flat pads of three middle fingers. Cover everything in overlapping vertical strips from collarbone to bra line and breastbone to armpit, using light, medium and firm pressure at each point. Repeat standing, and include the armpit.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">When in the month should I do a breast self-exam?</h3>
                        <p class="text-gray-700">Three to five days after your period ends, when breast tissue is least swollen and lumpy. Women who have reached menopause, are pregnant, or have irregular cycles should pick the same date each month and keep to it. Consistency matters more than the exact date, because the point is noticing change over time rather than grading a single examination.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What breast changes need a doctor's appointment this week?</h3>
                        <p class="text-gray-700">A new lump or thickening persisting through a full cycle; a hard, fixed, irregular lump; skin dimpling, puckering or orange-peel texture; a newly inverted nipple; blood-stained or clear spontaneous discharge from one nipple; persistent nipple scaling or eczema; a lump in the armpit or above the collarbone; one-sided change in size or shape; or redness and swelling that does not settle with antibiotics.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Are most breast lumps cancer?</h3>
                        <p class="text-gray-700">No. The large majority are benign, including fibroadenomas, simple cysts, fat necrosis and fibrocystic change. That is reassuring but not a reason to wait and watch alone. Benign and serious lumps are not reliably distinguishable by feel, which is exactly why a persistent lump deserves clinical examination and imaging.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What happens during a breast cancer work-up?</h3>
                        <p class="text-gray-700">Triple assessment. A clinician examines both breasts and armpits. Imaging follows, usually ultrasound under about 35 and mammography with or without ultrasound above that. If a lump needs further evaluation, a needle sample is taken under local anaesthesia and sent to the laboratory. Most patients complete examination and imaging in a single visit.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">At what age should breast cancer screening start in India?</h3>
                        <p class="text-gray-700">For average risk, clinical breast examination is generally advised from around 30 and screening mammography commonly discussed from 40, individualised in consultation. Indian women tend to present about a decade earlier than Western populations, so dismissing symptoms in someone in their thirties is a mistake. Strong family history usually means starting considerably earlier.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">When does family history mean earlier screening?</h3>
                        <p class="text-gray-700">If a first-degree relative had breast cancer, particularly before menopause; if two or more close relatives on one side had breast or ovarian cancer; if there is a known BRCA1 or BRCA2 change; if a male relative had breast cancer; or if a relative had cancer in both breasts. A common approach is starting about ten years before the youngest affected relative's diagnosis age, decided individually.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Can men get breast cancer?</h3>
                        <p class="text-gray-700">Yes, though far less commonly. Men have a small amount of breast tissue and can develop the same disease, and because it is rarely expected they often present later. A firm painless lump under the nipple, nipple retraction, skin change or discharge in a man should be examined promptly. Our guide to <a href="/blog/symptoms-of-cancer-in-men/" class="text-secondary-600 hover:underline font-semibold">cancer symptoms in men</a> covers the broader warning signs.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Does a self-exam replace a mammogram?</h3>
                        <p class="text-gray-700">No. A mammogram can detect changes years before anything is large enough to feel, which is why screening exists as a separate activity. Self-examination and clinical examination find what has become palpable. They are complementary, and treating one as a substitute for the other is the most common misunderstanding we correct in clinic.</p>
                    </div>
