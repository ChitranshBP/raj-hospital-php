                <!-- Introduction -->
                <p class="text-lg leading-relaxed text-gray-700 mb-6">
                    <strong>"My head is killing me"</strong> - we've all said it, but do you really know what type of head pain you're experiencing? Many people use the word "migraine" casually to describe any bad headache, but migraine is a distinct neurological condition that goes far beyond simple head pain. Understanding the difference between a common headache and a migraine can help you seek the right treatment and get relief faster.
                </p>

                <p class="text-gray-700 mb-6">
                    According to the World Health Organization, headaches are among the most common disorders of the nervous system, affecting nearly half of the adult population globally. Migraines alone affect about 1 billion people worldwide, making it one of the leading causes of disability. Despite this prevalence, many people suffer without proper diagnosis or treatment because they don't understand that their symptoms point to migraine rather than a simple tension headache.
                </p>

                <!-- Section 1: What is a Headache? -->
                <h2 class="raj-h2">Understanding Headaches</h2>

                <p class="text-gray-700 mb-4">
                    A <strong>headache</strong> is a broad term referring to pain in the head, face, or upper neck region. Headaches can be primary (the pain itself is the condition) or secondary (caused by another medical condition). The most common types include tension headaches, cluster headaches, and sinus headaches.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Types of Headaches</h3>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Tension Headaches</h4>
                        <p class="text-sm text-gray-600">The most common type, affecting about 70% of people. Caused by muscle tension in the head, neck, and shoulder region. Usually feels like a constant, dull ache on both sides of the head. Can last from 30 minutes to several hours.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Cluster Headaches</h4>
                        <p class="text-sm text-gray-600">One of the most painful types, characterized by severe burning or piercing pain, usually around one eye or one side of the face. Attacks last 15 minutes to 3 hours and can occur multiple times a day for weeks or months.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Sinus Headaches</h4>
                        <p class="text-sm text-gray-600">Caused by sinus inflammation or infection, resulting in pain in the forehead, cheeks, and bridge of the nose. Often accompanied by nasal congestion, fever, and facial swelling.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Exertional Headaches</h4>
                        <p class="text-sm text-gray-600">Triggered by physical activity such as running, coughing, sneezing, or sexual intercourse. Usually brief but can be intense.</p>
                    </div>
                </div>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Common Headache Symptoms</h3>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Dull, aching pain (tension) or sharp, stabbing pain (cluster)</li>
                    <li>Pain on both sides of the head (tension) or one side (cluster)</li>
                    <li>Tightness or pressure around the forehead</li>
                    <li>Pain that worsens with physical activity</li>
                    <li>No nausea, vomiting, or visual disturbances</li>
                </ul>

                <!-- Section 2: What is Migraine? -->
                <h2 class="raj-h2">Understanding Migraines</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Migraine</strong> is a neurological disease characterized by recurrent moderate to severe headaches, often accompanied by nausea, vomiting, and sensitivity to light, sound, or smell. It's not just "a bad headache" - it's a complex neurological condition that affects the entire nervous system.
                </p>

                <p class="text-gray-700 mb-6">
                    During a migraine attack, changes occur in the brain that lead to inflammation and activation of pain pathways. This explains why migraines cause much more than just head pain - they can affect multiple sensory systems and significantly impact daily life during an attack.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Migraine Phases</h3>
                <div class="space-y-4 mb-6">
                    <div class="raj-callout raj-callout-info">
                        <h4 class="font-bold text-purple-600 mb-2">1. Prodrome (Pre-headache)</h4>
                        <p class="text-sm text-gray-600">Hours to days before the migraine, you might experience mood changes, food cravings, neck stiffness, increased yawning, or difficulty concentrating. About 30% of migraine sufferers experience this warning phase.</p>
                    </div>
                    <div class="raj-callout raj-callout-info">
                        <h4 class="font-bold text-purple-600 mb-2">2. Aura (15-30 minutes before)</h4>
                        <p class="text-sm text-gray-600">Experienced by about 20% of migraine sufferers. Visual disturbances (flashing lights, blind spots), sensory changes (numbness, tingling), or speech difficulties. These symptoms gradually develop and then fade as the headache begins.</p>
                    </div>
                    <div class="raj-callout raj-callout-info">
                        <h4 class="font-bold text-purple-600 mb-2">3. Attack (4-72 hours)</h4>
                        <p class="text-sm text-gray-600">The main headache phase with throbbing pain (usually on one side), nausea, vomiting, and sensitivity to light, sound, and smell. Physical activity worsens the pain. Many people need to lie down in a dark, quiet room.</p>
                    </div>
                    <div class="raj-callout raj-callout-info">
                        <h4 class="font-bold text-purple-600 mb-2">4. Post-drome (24-48 hours after)</h4>
                        <p class="text-sm text-gray-600">The "migraine hangover." Feelings of exhaustion, confusion, or elation might persist. Some people report difficulty concentrating, scalp tenderness, or mood changes during this phase.</p>
                    </div>
                </div>

