                <!-- Section 4: Triggers -->
                <h2 class="raj-h2">Common Triggers</h2>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Headache Triggers</h3>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Stress and anxiety</li>
                    <li>Poor posture</li>
                    <li>Muscle tension in neck and shoulders</li>
                    <li>Eyestrain from screen use</li>
                    <li>Skipping meals or dehydration</li>
                    <li>Weather changes</li>
                    <li>Lack of sleep</li>
                </ul>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Migraine Triggers</h3>
                <p class="text-gray-700 mb-4">
                    Migraines have a much broader range of triggers, which is why identifying and avoiding them is a key part of migraine management:
                </p>

