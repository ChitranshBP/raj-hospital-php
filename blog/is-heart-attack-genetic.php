                    <strong>Is <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">heart attack</a> genetic?</strong> The honest answer from the cardiology team at <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">RAJ Hospital, the best hospital in Ranchi</a>, is "yes, partly." You do not inherit a <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">heart attack</a> the way you inherit eye colour, but the risk of having one is heavily influenced by the DNA you carry — and in some families, the genetic contribution is large enough to cause heart attacks in the 30s and 40s. This guide explains what the science says, when to consider genetic testing, and what to do if heart disease runs in your family.
                </p>

                <div class="raj-callout raj-callout-info">
                    <strong class="text-emerald-700">Quick Answer:</strong>
                    <span class="text-gray-700"> <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">Heart attack</a> is <strong>not directly inherited</strong>, but the risk is. A first-degree relative with premature <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">heart attack</a> (&lt;55 in men, &lt;65 in women) raises your risk <strong>2–7 times</strong>. Specific inherited conditions — familial hypercholesterolemia (FH), elevated Lp(a), HCM, Long QT — are 100% genetic and can cause heart attacks in young adults. If heart disease runs in your family, <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">book a preventive cardiology consultation at RAJ Hospital</a> by age 30.</span>
                </div>

                <h2 class="raj-h2">The Numbers — How Strong Is the Genetic Link?</h2>
                <p class="text-gray-700 mb-4">
                    A landmark 2007 study in the <em>New England Journal of Medicine</em> followed 20,000 Swedish twins for 36 years. The conclusion: <strong>genetics explained about 50% of the risk</strong> of coronary artery disease; the other half was environmental (lifestyle, smoking, diet, exercise). A more recent 2024 polygenic risk score analysis of 1.1 million participants (Klarin et al., <em>Nature Genetics</em>) identified 240 common gene variants that, taken together, can stratify a person from the bottom 20% to the top 20% lifetime risk.
                </p>
                <p class="text-gray-700 mb-4">
                    In practical terms at <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">RAJ Hospital's Family Heart Risk clinic</a>, a 35-year-old whose father had an MI at 47 and mother an MI at 52 carries roughly 4× the population risk. Adding a high Lp(a) increases it to 6×. Add smoking, and the risk doubles again.
                </p>

                <h2 class="raj-h2">Inherited Conditions That Directly Cause Heart Attacks</h2>
                <p class="text-gray-700 mb-4">
                    A small but important group of patients carry single-gene mutations that cause heart attacks even with perfect lifestyle. The <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">cardiologists at RAJ Hospital</a> screen for these:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-white border-l-4 border-emerald-500 p-4 rounded-r-lg">
                        <h4 class="font-bold text-emerald-700"><i data-feather="circle" class="raj-icon raj-icon-sm"></i> 1. Familial Hypercholesterolemia (FH)</h4>
                        <p class="text-sm text-gray-700 mt-1">Affects 1 in 250 people. LDL receptor, APOB or PCSK9 gene mutations cause very high LDL from birth. Untreated, the average heart-attack age is 35–45. Treatment: high-intensity statin + ezetimibe + PCSK9 inhibitor if needed. RAJ Hospital's lipid clinic runs a dedicated FH registry.</p>
                    </div>
                    <div class="bg-white border-l-4 border-emerald-500 p-4 rounded-r-lg">
                        <h4 class="font-bold text-emerald-700"><i data-feather="circle" class="raj-icon raj-icon-sm"></i> 2. Elevated Lipoprotein(a) — Lp(a)</h4>
                        <p class="text-sm text-gray-700 mt-1">Affects 20% of the population. LPA gene variants cause high Lp(a), which doubles heart attack risk independent of LDL. Should be measured once in every adult's life. No specific therapy yet, but very close — pelacarsen, an antisense drug in Phase-3 trials, will be available in India soon.</p>
                    </div>
                    <div class="bg-white border-l-4 border-emerald-500 p-4 rounded-r-lg">
                        <h4 class="font-bold text-emerald-700"><i data-feather="circle" class="raj-icon raj-icon-sm"></i> 3. Hypertrophic Cardiomyopathy (HCM)</h4>
                        <p class="text-sm text-gray-700 mt-1">Affects 1 in 500. Sarcomere gene mutations (MYH7, MYBPC3) cause a thickened heart muscle that can suddenly obstruct flow or trigger fatal arrhythmias. The leading cause of sudden cardiac death in young athletes. Diagnosed by echo and cardiac MRI; treated with beta-blockers, septal ablation, or ICD.</p>
                    </div>
                    <div class="bg-white border-l-4 border-emerald-500 p-4 rounded-r-lg">
                        <h4 class="font-bold text-emerald-700"><i data-feather="circle" class="raj-icon raj-icon-sm"></i> 4. Long QT, Brugada, CPVT</h4>
                        <p class="text-sm text-gray-700 mt-1">Inherited arrhythmia syndromes that can cause sudden cardiac arrest in otherwise healthy young people. Diagnosed on ECG, treated with beta-blockers, lifestyle changes, and an implantable cardioverter defibrillator (ICD) in high-risk cases.</p>
                    </div>
                </div>

                <h2 class="raj-h2">When Should You Get Genetic Testing?</h2>
                <p class="text-gray-700 mb-4">
                    Genetic testing is not for everyone — it is expensive, and the results can be ambiguous. The <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">preventive cardiology team at RAJ Hospital</a> recommends testing if you have any of the following:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>A first-degree relative with a heart attack before age 55 (men) or 65 (women)</li>
                    <li>Your own LDL cholesterol persistently above 190 mg/dL</li>
                    <li>Tendon xanthomas, corneal arcus before age 45, or xanthelasma</li>
                    <li>Unexplained sudden cardiac death in a family member under 40</li>
                    <li>Personal history of heart attack before age 50 with normal traditional risk factors</li>
                    <li>Recurrent pancreatitis or family history of high Lp(a)</li>
                </ul>

