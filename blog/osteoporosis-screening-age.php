            <div class="p-6 md:p-10">

                <p class="text-lg leading-relaxed text-gray-700 mb-6">
                    World Osteoporosis Day falls on <strong>20 October</strong>, and it marks a condition with an unusual problem: there is nothing to notice. No pain, no swelling, no symptom that would send anyone to a doctor. Bone quietly thins over fifteen or twenty years, and the first sign is a wrist that snaps after catching a doorframe, or a hip that breaks after a slip in a wet bathroom. By then the damage is decades old. The test that would have found it is a fifteen-minute scan that costs less than a small appliance, and almost nobody books it.
                </p>

                <div class="raj-callout raj-callout-info">
                    <strong class="text-secondary-600">The short version:</strong>
                    <span class="text-gray-700"> Get a bone density scan if you are a woman over 65 or a man over 70, or considerably earlier if you have any risk factor listed below. If you are past menopause and have <em>ever</em> broken a bone from a fall at standing height, you should have been scanned already. Our <a href="/specialties/radiology" class="text-secondary-600 hover:underline font-semibold">radiology department in Ranchi</a> can arrange this without a long wait.</span>
                </div>

                <h2 class="raj-h2"><i data-feather="eye-off" class="raj-h2-icon"></i> Why Osteoporosis Has No Symptoms Until a Fracture</h2>
                <p class="text-gray-700 mb-4">
                    Bone is not inert scaffolding. It is living tissue in constant turnover, with cells called osteoclasts removing old bone and osteoblasts laying down new bone. Through youth, building outpaces removal. Peak bone mass is reached around the late twenties. After that the two roughly balance for a couple of decades, and then removal starts to win.
                </p>
                <p class="text-gray-700 mb-4">
                    In women, this tips sharply at menopause. Oestrogen restrains the bone-removing cells, and when it falls, they work unopposed. The years immediately around and after menopause see the steepest bone loss of a woman's life, and it happens with no sensation whatsoever, because <strong>bone tissue itself has no pain fibres inside it</strong>. Pain comes from the periosteum covering the bone, from muscle and from nerves, none of which are affected by thinning within. A bone can lose a third of its density and feel exactly like it did at thirty.
                </p>
                <p class="text-gray-700 mb-4">
                    What you might notice, if you are paying close attention over years, are indirect clues rather than symptoms:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Loss of height.</strong> More than two or three centimetres below your peak adult height suggests spinal compression fractures. Worth measuring at each check-up, and almost never measured.</li>
                    <li><strong>A stooping upper back.</strong> A gradually rounded posture is often assumed to be poor habit but can reflect wedged vertebrae.</li>
                    <li><strong>New persistent back pain</strong> in an older adult, particularly starting suddenly, which may be a spinal compression fracture. Our guide on <a href="/blog/back-pain-when-to-get-mri/" class="text-secondary-600 hover:underline font-semibold">when back pain needs a scan</a> covers this overlap.</li>
                    <li><strong>A fracture from a trivial fall.</strong> The clearest signal of all. A healthy adult bone should not break from a fall from standing height. When it does, that is osteoporosis until proven otherwise, and it should trigger a scan rather than just a plaster cast.</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    That last point deserves emphasis. A wrist fracture in a 58-year-old woman who slipped on a step is frequently treated as an orthopaedic accident and nothing more. It is actually a warning that the next fracture may be a hip, and hip fractures in older adults carry serious consequences for independence and for life expectancy.
                </p>

                <h2 class="raj-h2"><i data-feather="user-check" class="raj-h2-icon"></i> Who Should Actually Get Screened, and at What Age</h2>

                <figure class="my-6">
                    <img src="/blog/assets/img/osteoporosis-screening-doctor-consultation.jpg"
                         alt="Doctor discussing a health chart with a patient during a consultation about bone density screening"
                         width="1200" height="675" loading="lazy" class="w-full rounded-lg shadow-sm">
                    <figcaption class="text-sm text-gray-500 mt-2 text-center">Screening age is not one number. Risk factors move it forward, sometimes by fifteen years.</figcaption>
                </figure>

                <p class="text-gray-700 mb-4">
                    The default guidance is <strong>women from 65 and men from 70</strong> at average risk. But almost nobody in the group that most needs testing is at average risk, and applying the default blindly means missing the people the test exists for. Ask for a scan considerably earlier if any of the following apply:
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="alert-triangle" class="raj-icon raj-icon-md raj-icon-red"></i> Strong reasons to test early</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Any fracture after a fall from standing height, at any age past 50</li>
                            <li>Menopause before 45, or surgical removal of the ovaries</li>
                            <li>Steroid tablets for three months or longer, at any age</li>
                            <li>A parent who fractured a hip</li>
                            <li>Height loss of more than 3 cm, or a new stooped posture</li>
                        </ul>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="info" class="raj-icon raj-icon-md raj-icon-yellow"></i> Other risk factors worth flagging</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Low body weight or a small frame</li>
                            <li>Smoking, or more than moderate alcohol intake</li>
                            <li>Rheumatoid arthritis and other inflammatory conditions</li>
                            <li>Overactive <a href="/blog/thyroid-symptoms-in-hindi/" class="text-secondary-600 hover:underline">thyroid</a> or parathyroid disease</li>
                            <li>Chronic kidney or liver disease, coeliac disease, or bariatric surgery</li>
                            <li>Long-term untreated <a href="/blog/vitamin-d-ki-kami-ke-lakshan/" class="text-secondary-600 hover:underline">vitamin D deficiency</a></li>
                            <li>Type 1 diabetes, and some long-term medications</li>
                        </ul>
                    </div>
                </div>
                <p class="text-gray-700 mb-4 mt-4">
                    Two groups are consistently under-tested in India. The first is <strong>post-menopausal women in their fifties</strong>, who are told they are too young for a bone scan while sitting in the very decade when bone loss is fastest. The second is <strong>men</strong>. Osteoporosis is thought of as a women's disease, so men are rarely screened and are frequently diagnosed only after a fracture, at which point outcomes are worse than in women.
                </p>
                <p class="text-gray-700 mb-4">
                    A note specific to this region: <a href="/blog/low-vitamin-d-symptoms-female/" class="text-secondary-600 hover:underline font-semibold">vitamin D deficiency is very common across India</a>, including in sunny states, because of indoor work, covering clothing, air pollution and naturally darker skin, which needs longer sun exposure to make the same amount. Vitamin D deficiency undermines calcium absorption regardless of how much calcium is eaten, which makes it a foundational issue rather than an optional supplement.
                </p>

                <h2 class="raj-h2"><i data-feather="activity" class="raj-h2-icon"></i> What a DEXA Scan Involves: Quick, Painless, Low Radiation</h2>
                <p class="text-gray-700 mb-4">
                    Much of the reluctance to book this test comes from imagining something it is not. People picture a tunnel, an injection, or a long uncomfortable procedure. None of that applies.
                </p>
                <p class="text-gray-700 mb-4">
                    DEXA stands for dual-energy X-ray absorptiometry. Two X-ray beams of different energies pass through the body, and because bone and soft tissue absorb them differently, the machine can calculate bone mineral density precisely.
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>You stay fully clothed</strong>, minus metal items such as belts, zips and jewellery.</li>
                    <li><strong>You lie on an open padded table.</strong> No tunnel, no enclosed space, nothing touching you. A scanning arm passes above the body.</li>
                    <li><strong>Two sites are measured</strong>, usually the lower spine and the hip, since these are where fractures matter most and where density is most predictive.</li>
                    <li><strong>It takes about ten to fifteen minutes</strong> and is completely painless.</li>
                    <li><strong>Radiation is very low</strong>, considerably less than a standard chest X-ray, and a small fraction of what a CT scan involves.</li>
                    <li><strong>No preparation is needed</strong> beyond avoiding calcium supplements for about 24 hours beforehand, since they can interfere with the reading.</li>
                    <li><strong>Results the same day</strong> in most cases, discussed alongside your other risk factors.</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    <strong>Reading the report.</strong> The key figure is the T-score, which compares your density with a healthy young adult:
                </p>
                <div class="raj-grid raj-grid-3">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="check-circle" class="raj-icon raj-icon-md raj-icon-green"></i> Above &minus;1.0</h3>
                        <p class="text-sm text-gray-700">Normal bone density. Continue calcium, vitamin D and weight-bearing exercise, and repeat testing at an interval your doctor advises.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="alert-circle" class="raj-icon raj-icon-md raj-icon-yellow"></i> &minus;1.0 to &minus;2.5</h3>
                        <p class="text-sm text-gray-700">Osteopenia: lower than ideal, not yet osteoporosis. This is the most useful result to receive, because there is time to act before a fracture happens.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="alert-octagon" class="raj-icon raj-icon-md raj-icon-red"></i> &minus;2.5 or below</h3>
                        <p class="text-sm text-gray-700">Osteoporosis. Treatment is usually indicated alongside lifestyle measures, and the goal shifts to actively reducing fracture risk.</p>
                    </div>
                </div>
                <p class="text-gray-700 mb-4 mt-4">
                    An important caveat: the T-score is not the whole answer. Fracture risk also depends on age, previous fractures, steroid use, smoking and family history, and clinicians combine the number with a formal risk assessment. Some patients with osteopenia have a higher fracture risk than some with osteoporosis, which is why treatment decisions are never made from a single figure. Blood tests usually run alongside to check calcium, vitamin D, kidney function and thyroid status through our <a href="/specialties/laboratory-investigations" class="text-secondary-600 hover:underline font-semibold">laboratory</a>.
                </p>

                <h2 class="raj-h2"><i data-feather="shield" class="raj-h2-icon"></i> Prevention: What Actually Helps, and What Does Not</h2>

                <figure class="my-6">
                    <img src="/blog/assets/img/senior-fitness-class-bone-strength.jpg"
                         alt="Senior woman taking part in an indoor fitness class, the kind of weight-bearing exercise that supports bone strength"
                         width="1200" height="675" loading="lazy" class="w-full rounded-lg shadow-sm">
                    <figcaption class="text-sm text-gray-500 mt-2 text-center">Bone responds to load. Swimming is excellent for you, but it does not build bone.</figcaption>
                </figure>

                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="coffee" class="raj-icon raj-icon-md raj-icon-blue"></i> Calcium, mostly from food</h3>
                        <p class="text-sm text-gray-700">Most adults need roughly 1000 to 1200 mg daily. Milk, curd, paneer, ragi, sesame seeds, almonds, green leafy vegetables, and small fish eaten with bones. Food sources are better absorbed and carry fewer downsides than large supplement doses, which should be taken only on advice.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="sun" class="raj-icon raj-icon-md raj-icon-yellow"></i> Vitamin D, guided by a blood level</h3>
                        <p class="text-sm text-gray-700">Without it, dietary calcium is poorly absorbed no matter how much you eat. Deficiency is widespread in India. Requirements vary enough between people that dosing should follow a measured level rather than a guess or a neighbour's prescription.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="trending-up" class="raj-icon raj-icon-md raj-icon-green"></i> Weight-bearing and resistance exercise</h3>
                        <p class="text-sm text-gray-700">Bone strengthens in response to load. Brisk walking, stair climbing, dancing, and resistance work with weights or bands two to three times a week. Swimming and cycling protect the heart and joints but do not load bone and therefore do not build density.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="home" class="raj-icon raj-icon-md raj-icon-secondary"></i> Preventing the fall</h3>
                        <p class="text-sm text-gray-700">The most neglected half of the problem. Anti-slip mats in bathrooms, grab bars, good lighting on stairs, removing loose rugs and trailing wires, an annual eye check, reviewing medicines that cause dizziness, and balance practice such as tai chi. No fall, no fracture.</p>
                    </div>
                </div>
                <p class="text-gray-700 mb-4 mt-4">
                    Things that actively harm bone and are worth addressing: smoking, more than moderate alcohol, very low body weight or restrictive dieting, prolonged inactivity, and excessive caffeine on a low-calcium diet. Also relevant is protein intake, which is frequently too low in older Indian adults and matters for both bone matrix and the muscle that protects against falls. Our <a href="/specialties/nutrition-and-dietetics" class="text-secondary-600 hover:underline font-semibold">dietetics team</a> can build a realistic plan around an existing diet rather than replacing it.
                </p>

                <h2 class="raj-h2"><i data-feather="clipboard" class="raj-h2-icon"></i> What Treatment Looks Like if Bone Density Is Already Low</h2>
                <p class="text-gray-700 mb-4">
                    A diagnosis of osteoporosis is not a sentence to fragility. Bone density can genuinely improve with treatment, and fracture risk falls faster than the density number itself rises.
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Correct the foundations first.</strong> Vitamin D deficiency and low calcium intake are addressed before or alongside any bone medication, because treatment works poorly without them.</li>
                    <li><strong>Look for a treatable cause.</strong> Overactive thyroid or parathyroid, coeliac disease, kidney disease, low testosterone in men, and steroid use are all reversible contributors that change the plan if found. Our <a href="/specialties/internal-medicine" class="text-secondary-600 hover:underline font-semibold">internal medicine team</a> works through these.</li>
                    <li><strong>Bone-preserving medication.</strong> Several classes exist, including drugs that slow bone removal and, for severe cases, drugs that actively stimulate bone formation. They differ in how they are taken, from daily or weekly tablets to injections given every six months or yearly. Choice depends on severity, kidney function, other conditions and what a patient will realistically stick to.</li>
                    <li><strong>Follow-up scanning.</strong> Bone density is usually rechecked after one to two years to confirm the treatment is working, since the effect is invisible without measurement.</li>
                    <li><strong>Fracture care when needed.</strong> If a fracture has already happened, treatment involves both fixing the break through our <a href="/specialties/orthopaedics-and-joint-replacement" class="text-secondary-600 hover:underline font-semibold">orthopaedics and joint replacement service</a> and treating the underlying bone disease, which is the step most often forgotten. Rehabilitation through <a href="/specialties/physiotherapy-and-rehabilitation" class="text-secondary-600 hover:underline font-semibold">physiotherapy</a> restores strength and reduces the chance of the next fall.</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    Two practical points that come up constantly. First, tablet bisphosphonates have specific instructions, typically taken on an empty stomach with a full glass of plain water while remaining upright for at least half an hour. These instructions exist to prevent oesophageal irritation and are not optional. Second, tell your dentist you are on bone medication before any extraction or implant. It rarely changes anything, but it is information the dental team should have, and our <a href="/specialties/dental" class="text-secondary-600 hover:underline font-semibold">dental department</a> coordinates on this routinely.
                </p>

