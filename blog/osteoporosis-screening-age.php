                <h2 class="raj-h2"><i data-feather="message-circle" class="raj-h2-icon"></i> Frequently Asked Questions</h2>
                <div class="space-y-4">
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">At what age should you get screened for osteoporosis?</h3>
                        <p class="text-gray-700">Commonly from 65 in women and 70 in men at average risk, but considerably earlier with additional risk factors, often from menopause in women. Earlier testing is justified by early menopause before 45, a parent who fractured a hip, long-term steroid use, low body weight, smoking, heavy alcohol, rheumatoid arthritis, thyroid or parathyroid overactivity, or any fracture after a fall from standing height.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What is a DEXA scan and what does it involve?</h3>
                        <p class="text-gray-700">Dual-energy X-ray absorptiometry. You lie fully clothed on an open padded table while a scanning arm passes above you, usually measuring the lower spine and hip. No tunnel, no injection, no dye. It takes ten to fifteen minutes, is painless, and uses a very small radiation dose, far less than a chest X-ray. Avoid calcium supplements for about 24 hours beforehand.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What does a T-score mean on a bone density report?</h3>
                        <p class="text-gray-700">It compares your bone density with a healthy young adult. Minus 1.0 or above is normal. Between minus 1.0 and minus 2.5 is osteopenia, lower than ideal but not osteoporosis. Minus 2.5 or below is osteoporosis. The score is not the whole picture, since fracture risk also depends on age, previous fractures, steroid use and family history.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Does osteoporosis have any symptoms before a fracture?</h3>
                        <p class="text-gray-700">Usually not. Bone loss itself is painless, which is why it is called a silent disease. Some people notice gradual height loss, a stooped upper back, or new persistent back pain from small spinal compression fractures. Most have no warning until a wrist, hip or spine breaks after a fall that should not have caused a fracture.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">How much calcium and vitamin D do adults need for bone health?</h3>
                        <p class="text-gray-700">Roughly 1000 to 1200 mg of calcium daily for most adults, ideally from milk, curd, paneer, ragi, sesame, green leafy vegetables and small fish eaten with bones. Vitamin D is needed for calcium to be absorbed at all, and deficiency is common in India despite the sunshine. Vitamin D dosing should follow a measured blood level rather than guesswork.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What exercise actually strengthens bone?</h3>
                        <p class="text-gray-700">Bone responds to load. Brisk walking, stair climbing, dancing and jogging where joints allow, plus resistance training with weights or bands two or three times a week. Swimming and cycling are excellent for heart and joints but do not load bone and so do not build density. Balance work matters too, because preventing the fall prevents the fracture.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Can osteoporosis be reversed or only slowed?</h3>
                        <p class="text-gray-700">Density can genuinely improve, not merely hold steady. Medication combined with adequate calcium, corrected vitamin D and weight-bearing exercise increases density measurably over one to two years in most patients, and more importantly reduces fracture risk. Complete restoration to young-adult density is unusual, but substantially lower fracture risk is realistic.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Do men get osteoporosis?</h3>
                        <p class="text-gray-700">Yes. It is more common in women because of the oestrogen fall at menopause, but men develop it too, particularly after 70 or earlier with steroid use, low testosterone, heavy alcohol, smoking or chronic kidney or liver disease. Because it is seen as a women's disease, men are screened less and often diagnosed only after a fracture, when outcomes are worse.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">How often should a bone density scan be repeated?</h3>
                        <p class="text-gray-700">It depends on the first result and on whether treatment has started. A normal scan in someone at low risk may not need repeating for several years. Osteopenia is often rechecked after about two years. Someone on treatment is usually rescanned after one to two years to confirm it is working. Your doctor sets the interval based on your result and risk profile, not a fixed rule.</p>
                    </div>
