                <h2 class="raj-h2"><i data-feather="link" class="raj-h2-icon"></i> The Depression–Heart Connection: What the Evidence Says</h2>
                <p class="text-gray-700 mb-4">
                    Large, long-term studies consistently find that people with clinical depression have a higher rate of developing coronary heart disease and heart attacks than those without — even after accounting for smoking, weight and other risks. Major cardiology and psychiatry bodies now recognise depression as a risk factor that deserves attention alongside cholesterol and blood pressure. The effect is strongest in people with persistent, untreated major depression rather than a brief low mood.
                </p>
                <p class="text-gray-700 mb-4">
                    Importantly, this is not about "feeling sad." Depression is a medical condition affecting the whole body — the nervous system, hormones, immune function and behaviour. It is those body-wide effects, sustained over months and years, that quietly raise cardiac risk.
                </p>

                <h2 class="raj-h2"><i data-feather="activity" class="raj-h2-icon"></i> How Depression Damages the Heart — The Mechanisms</h2>
                <p class="text-gray-700 mb-4">
                    Cardiologists describe several overlapping pathways by which depression translates into heart risk. Some are biological, some behavioural — and they reinforce each other.
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="thermometer" class="raj-icon raj-icon-md raj-icon-red"></i> Chronic inflammation</h3>
                        <p class="raj-card-body">Depression is linked to raised inflammatory markers (such as CRP and IL-6). Inflammation destabilises plaque inside coronary arteries, making a blockage more likely.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="zap" class="raj-icon raj-icon-md raj-icon-red"></i> Stress hormones</h3>
                        <p class="raj-card-body">Persistently high cortisol and adrenaline raise blood pressure and heart rate and promote belly fat and insulin resistance — all bad for arteries.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="droplet" class="raj-icon raj-icon-md raj-icon-red"></i> Stickier blood</h3>
                        <p class="raj-card-body">Depression increases platelet activation, making the blood more prone to clotting — the immediate cause of most heart attacks.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="heart" class="raj-icon raj-icon-md raj-icon-red"></i> Nervous-system imbalance</h3>
                        <p class="raj-card-body">Reduced heart-rate variability and an overactive "fight-or-flight" system make the heart more vulnerable to dangerous rhythms.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="coffee" class="raj-icon raj-icon-md raj-icon-secondary"></i> Unhealthy coping</h3>
                        <p class="raj-card-body">Depression makes it harder to exercise, cook well or sleep, and easier to smoke, drink or overeat — compounding every other risk factor.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="x-circle" class="raj-icon raj-icon-md raj-icon-secondary"></i> Skipping treatment</h3>
                        <p class="raj-card-body">People who are depressed are less likely to take blood pressure, sugar or cholesterol medicines consistently — a major, often-missed driver of cardiac events.</p>
                    </div>
                </div>

                <h2 class="raj-h2"><i data-feather="repeat" class="raj-h2-icon"></i> It Works Both Ways: Heart Attacks Can Cause Depression Too</h2>
                <p class="text-gray-700 mb-4">
                    The relationship is a two-way street. Surviving a heart attack, being diagnosed with heart failure, or living with chest pain is frightening and life-changing — and about <strong>one in five</strong> heart patients go on to develop depression. This "cardiac depression" is not a sign of weakness; it is common and treatable.
                </p>
                <p class="text-gray-700 mb-4">
                    It also matters medically: depression after a heart attack is linked to slower recovery, less participation in rehabilitation, and a higher risk of a second event. That is exactly why the <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">cardiology team at RAJ Hospital Ranchi</a> screens heart patients for mood problems and treats them as part of complete cardiac care — not as an afterthought.
                </p>

                <h2 class="raj-h2"><i data-feather="alert-triangle" class="raj-h2-icon"></i> Depression vs Heart Attack Symptoms — Don't Confuse Them</h2>
                <p class="text-gray-700 mb-4">
                    Depression and heart problems can share symptoms like fatigue, chest heaviness, breathlessness and poor sleep — which sometimes leads people to dismiss genuine cardiac warning signs as "just stress." Know the difference.
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="cloud" class="raj-icon raj-icon-md raj-icon-secondary"></i> Signs of Depression</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Low mood or hopelessness most days for 2+ weeks</li>
                            <li>Loss of interest in things you enjoyed</li>
                            <li>Fatigue, poor concentration, disturbed sleep</li>
                            <li>Change in appetite or weight</li>
                            <li>Feelings of worthlessness or guilt</li>
