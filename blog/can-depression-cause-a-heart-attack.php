                        <h3 class="raj-card-title"><i data-feather="alert-triangle" class="raj-icon raj-icon-md raj-icon-red"></i> Signs of a Heart Attack</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Chest pressure, tightness or heaviness</li>
                            <li>Pain spreading to left arm, jaw, neck or back</li>
                            <li>Cold sweat, nausea, sudden breathlessness</li>
                            <li>Lightheadedness or fainting</li>
                            <li>Symptoms lasting more than 5 minutes</li>
                            <li>Often comes on with exertion or at rest</li>
