                <h2 class="raj-h2"><i data-feather="trending-up" class="raj-h2-icon"></i> Why Are Heart Attacks Rising in Young Adults?</h2>
                <p class="text-gray-700 mb-4">
                    Indian and global cardiology registries have recorded a clear shift: a growing share of heart attacks now occur in people aged 25–45. Studies of Indian patients repeatedly find that South Asians develop coronary artery disease <strong>about 10 years earlier</strong> than European populations, and often present with their first heart attack in their 30s and 40s. This is not simply "more testing" — it reflects a real change in how young hearts are exposed to risk.
                </p>
                <p class="text-gray-700 mb-4">
                    The reasons are layered. A desk-bound, screen-heavy routine has replaced physical activity. Tobacco, hookah and vaping remain common. Ultra-processed food, sugary drinks and late-night eating have pushed up rates of obesity, fatty liver and pre-diabetes in the young. Add chronic work stress, poor sleep, and a genetic tendency toward high <em>Lipoprotein(a)</em> and diabetes, and you have a population whose arteries are ageing faster than their birth certificates suggest.
                </p>

                <h2 class="raj-h2"><i data-feather="alert-circle" class="raj-h2-icon"></i> The Main Causes of Heart Attacks in Young People</h2>
                <p class="text-gray-700 mb-4">
                    A heart attack happens when blood flow to part of the heart muscle is suddenly blocked. In young people, that blockage can come from several distinct mechanisms — not always the classic "clogged artery" you might expect.
                </p>

                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="activity" class="raj-icon raj-icon-md raj-icon-red"></i> Premature Coronary Artery Disease</h3>
                        <p class="raj-card-body">Plaque builds up early because of smoking, diabetes, high LDL cholesterol, high blood pressure and family history. This is the single most common cause and is largely lifestyle- and genetics-driven.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="git-branch" class="raj-icon raj-icon-md raj-icon-secondary"></i> SCAD (Coronary Artery Dissection)</h3>
                        <p class="raj-card-body">A sudden tear in a coronary artery wall — a leading cause of heart attack in young women, especially during or after pregnancy. It can strike people with no traditional risk factors at all.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="dna" class="raj-icon raj-icon-md raj-icon-secondary"></i> Familial Hypercholesterolemia</h3>
                        <p class="raj-card-body">An inherited disorder causing very high LDL cholesterol from birth. Untreated, it can cause heart attacks in the 30s and 40s. It is under-diagnosed and runs in families.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="zap" class="raj-icon raj-icon-md raj-icon-red"></i> Cocaine &amp; Stimulant Use</h3>
                        <p class="raj-card-body">Cocaine, amphetamines and even high-dose energy stimulants can cause intense coronary spasm and clot formation, triggering a heart attack in an otherwise clean artery.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="wind" class="raj-icon raj-icon-md raj-icon-secondary"></i> Coronary Artery Spasm</h3>
                        <p class="raj-card-body">A temporary, intense tightening of an artery (Prinzmetal angina) that briefly cuts off blood flow. Triggers include stress, cold, smoking and certain drugs.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="alert-triangle" class="raj-icon raj-icon-md raj-icon-red"></i> Clotting &amp; Other Causes</h3>
                        <p class="raj-card-body">Inherited clotting disorders, severe COVID-related inflammation, congenital coronary anomalies and untreated Kawasaki disease from childhood can all raise heart-attack risk in the young.</p>
                    </div>
                </div>

                <h2 class="raj-h2"><i data-feather="list" class="raj-h2-icon"></i> Risk Factors You Can — and Can't — Change</h2>
                <p class="text-gray-700 mb-4">
                    Understanding your personal risk is the first step to prevention. Cardiologists split risk factors into two groups.
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="check-circle" class="raj-icon raj-icon-md raj-icon-green"></i> Modifiable (you control these)</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Smoking, hookah and vaping</li>
                            <li>Uncontrolled diabetes or pre-diabetes</li>
                            <li>High blood pressure</li>
                            <li>High LDL and low HDL cholesterol</li>
                            <li>Obesity, especially belly fat</li>
                            <li>Physical inactivity</li>
                            <li>Chronic stress and poor sleep</li>
                            <li>Excess alcohol and recreational drugs</li>
                        </ul>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="lock" class="raj-icon raj-icon-md raj-icon-gray"></i> Non-modifiable (screen for these)</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Family history of early heart disease (a parent/sibling before 55 in men, 65 in women)</li>
                            <li>South Asian ethnicity</li>
                            <li>Male sex (earlier risk) and post-menopausal women</li>
                            <li>High Lipoprotein(a) — inherited</li>
                            <li>Familial hypercholesterolemia</li>
                            <li>History of Kawasaki disease or congenital heart conditions</li>
                        </ul>
                    </div>
                </div>
                <p class="text-gray-700 mb-4">
                    You cannot change your genes — but you <em>can</em> know your numbers and act early. If a close relative had a heart attack young, that is exactly the reason to get screened, not a reason to assume it is inevitable. Read our detailed guide on <a href="/blog/is-heart-attack-genetic.php" class="text-secondary-600 hover:underline font-semibold">whether heart attacks are genetic</a> to understand your inherited risk.
                </p>

                <h2 class="raj-h2"><i data-feather="alert-triangle" class="raj-h2-icon"></i> Warning Signs Young People Wrongly Ignore</h2>
                <p class="text-gray-700 mb-4">
                    The tragedy of heart attacks in the young is how often the symptoms are brushed off as gas, acidity, anxiety or a gym strain. Because "I'm too young for a heart attack" is such a common thought, precious time is lost. Watch for:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Chest pressure, tightness or heaviness</strong> — often central, not a sharp pinpoint pain.</li>
                    <li><strong>Pain spreading</strong> to the left arm, both arms, jaw, neck, upper back or stomach.</li>
                    <li><strong>Sudden breathlessness</strong>, with or without chest pain.</li>
                    <li><strong>Cold sweat, nausea or vomiting</strong> — frequently mistaken for food poisoning.</li>
                    <li><strong>Unusual fatigue</strong> or feeling faint during light activity.</li>
                    <li><strong>Palpitations</strong> with dizziness that don't settle.</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    Chest discomfort is confusing because so many harmless things cause it too. Our guides on the <a href="/blog/difference-between-gas-pain-and-heart-attack-symptoms.php" class="text-secondary-600 hover:underline font-semibold">difference between gas pain and heart attack</a> and whether <a href="/blog/can-anxiety-cause-a-heart-attack.php" class="text-secondary-600 hover:underline font-semibold">anxiety can cause a heart attack</a> can help you tell them apart — but if you are unsure, always err on the side of caution.
                </p>

                <div class="raj-callout raj-callout-danger">
                    <i data-feather="phone-call" class="raj-callout-icon"></i>
                    <div class="raj-callout-body">
                        <strong>Call for emergency help immediately if:</strong> chest pain lasts more than 5 minutes, spreads to the arm or jaw, comes with cold sweat, breathlessness or fainting — <em>at any age</em>. Do not drive yourself. Rush to the <a href="https://rajhospitals.com/contact.php" class="text-secondary-600 hover:underline font-semibold">cardiac emergency unit at RAJ Hospital Ranchi</a> or the nearest hospital. Every minute of delay costs heart muscle.
