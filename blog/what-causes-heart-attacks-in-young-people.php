                <h2 class="raj-h2"><i data-feather="search" class="raj-h2-icon"></i> How Doctors Assess Heart Risk in Young Patients</h2>
                <p class="text-gray-700 mb-4">
                    You do not need to wait for symptoms to know where you stand. At RAJ Hospital, a young-heart risk assessment is quick and affordable, and typically includes:
                </p>
                <ol class="list-decimal list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Blood pressure and BMI/waist measurement</strong> — the simplest, most predictive screen.</li>
                    <li><strong>Fasting blood sugar and HbA1c</strong> — to catch silent diabetes and pre-diabetes.</li>
                    <li><strong>Lipid profile</strong> — LDL, HDL, triglycerides; and <strong>Lipoprotein(a)</strong> once in a lifetime if there is family history.</li>
                    <li><strong>ECG</strong>, and an <strong>echocardiogram or treadmill test</strong> if indicated.</li>
                    <li><strong>Family-history review</strong> — early heart disease in relatives changes the whole risk picture.</li>
                </ol>
                <p class="text-gray-700 mb-4">
                    Based on the results, the <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">cardiology team at RAJ Hospital Ranchi</a> can advise whether you simply need lifestyle changes or medication such as a statin to protect your arteries for the decades ahead.
                </p>

                <h2 class="raj-h2"><i data-feather="shield" class="raj-h2-icon"></i> How to Prevent a Heart Attack When You're Young</h2>
                <p class="text-gray-700 mb-4">
                    The encouraging news: the large majority of premature heart attacks are preventable. Prevention in your 20s and 30s pays off enormously by your 50s.
                </p>
                <div class="raj-grid raj-grid-3">
                    <div class="raj-card raj-card-text-center">
                        <i data-feather="x-octagon" class="raj-card-icon mx-auto"></i>
                        <h3 class="raj-card-title">Quit all tobacco</h3>
