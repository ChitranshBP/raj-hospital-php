                <h1 class="text-2xl md:text-3xl font-bold text-gray-800 mb-4">Why Am I Experiencing Excessive Hair Fall? Common Causes and Treatments</h1>
                <?php include $base_url . 'components/medical-disclaimer.php'; ?>
                <div class="flex flex-wrap items-center gap-4 text-sm text-gray-500">
                    <span class="flex items-center gap-1"><i data-feather="clock" class="w-4 h-4"></i> 8 min read</span>
