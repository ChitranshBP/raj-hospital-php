                <!-- Section 4: Specific Differences -->
                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-secondary-600 pb-2 mt-8 mb-4">Detailed Comparison of Symptoms</h2>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Pain Quality</h3>
                <p class="text-gray-700 mb-4">
                    <strong>Gas Pain:</strong> Often described as sharp, jabbing, or knife-like. The pain might come in waves and move around the abdominal area. Some people describe it as feeling like a bubble moving inside their chest.
                </p>
                <p class="text-gray-700 mb-6">
                    <strong>Heart Attack Pain:</strong> Typically described as pressure, squeezing, tightness, or an elephant sitting on your chest. The pain is usually constant and doesn't move or change with breathing or position changes.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Pain Location and Radiation</h3>
                <p class="text-gray-700 mb-4">
                    <strong>Gas Pain:</strong> Usually starts in the abdomen and might spread to the chest. Rarely radiates to the jaw, neck, or left arm. May be relieved by pressing on the abdomen.
                </p>
                <p class="text-gray-700 mb-6">
                    <strong>Heart Attack Pain:</strong> Starts in the chest and often spreads to the left arm, shoulder, neck, jaw, or back. NOT relieved by pressing on the chest or changing position.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Response to Activity and Position</h3>
                <p class="text-gray-700 mb-4">
                    <strong>Gas Pain:</strong> May change with position, deep breathing, or belching. Movement doesn't typically make it worse.
                </p>
                <p class="text-gray-700 mb-6">
                    <strong>Heart Attack Pain:</strong> Often worsens with physical activity and doesn't improve with position changes. Deep breathing might increase the pain.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Associated Symptoms</h3>
                <p class="text-gray-700 mb-4">
                    <strong>Gas Pain:</strong> Bloating, excessive burping or flatulence, stomach rumbling, relief after bowel movement.
                </p>
                <p class="text-gray-700 mb-6">
                    <strong>Heart Attack:</strong> Cold, clammy skin, shortness of breath, lightheadedness, nausea, sudden fatigue. Women might experience more subtle symptoms like unusual fatigue, sleep disturbances, and anxiety.
                </p>

                <!-- Section 5: Special Cases -->
                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-secondary-600 pb-2 mt-8 mb-4">Women May Experience Different Symptoms</h2>

                <p class="text-gray-700 mb-4">
                    It's crucial to understand that heart attack symptoms in women can be different from the classic "male" symptoms. Women are more likely to experience:
                </p>

                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Unusual fatigue that comes on suddenly</li>
                    <li>Sleep disturbances</li>
                    <li>Shortness of breath without chest pain</li>
                    <li>Nausea or vomiting</li>
                    <li>Back or jaw pain</li>
                    <li>Indigestion-like symptoms</li>
                    <li>Anxiety or sense of impending doom</li>
                </ul>

                <div class="bg-blue-50 border-l-4 border-blue-500 p-4 rounded-r-lg mb-6">
                    <strong class="text-blue-700">Important:</strong>
                    <span class="text-gray-700"> Women often dismiss their symptoms as indigestion, stress, or normal aging. This leads to delayed treatment and worse outcomes. When something feels "wrong," trust your instincts and seek medical help.</span>
                </div>

                <!-- Section 6: When to Seek Emergency Care -->
                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-secondary-600 pb-2 mt-8 mb-4">When to Call Emergency Services</h2>

                <p class="text-gray-700 mb-4">
                    Don't try to "tough it out" or drive yourself to the hospital if you suspect a heart attack. Call emergency services immediately if you experience:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-red-50 p-4 rounded-lg border-l-4 border-red-500">
