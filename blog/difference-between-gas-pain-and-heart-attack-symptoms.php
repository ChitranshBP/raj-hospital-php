                <!-- Section 1: Understanding Gas Pain -->
                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-secondary-600 pb-2 mt-8 mb-4">Understanding Gas Pain</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Gas pain</strong>, also known as flatulence or bloating, is a normal part of the digestive process. Everyone produces gas - on average, a person passes gas 13-21 times per day. However, when gas builds up in the digestive system, it can cause significant discomfort that sometimes radiates to the chest area, creating confusion with cardiac symptoms.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Common Causes of Gas Pain</h3>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Swallowed Air</strong> - Eating too fast, chewing gum, drinking carbonated beverages</li>
                    <li><strong>Food Intolerances</strong> - Lactose intolerance, gluten sensitivity</li>
                    <li><strong>High-Fiber Foods</strong> - Beans, cabbage, Brussels sprouts, onions</li>
                    <li><strong>Digestive Disorders</strong> - IBS, GERD, small intestinal bacterial overgrowth</li>
                    <li><strong>Carbonated Drinks</strong> - Soda, beer, sparkling water</li>
                    <li><strong>Artificial Sweeteners</strong> - Sorbitol, mannitol in sugar-free products</li>
                </ul>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Characteristics of Gas Pain</h3>
                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">Location and Radiation</h4>
                        <p class="text-sm text-gray-600">Gas pain typically stays in the abdominal area but can radiate upward to the chest and left shoulder. It's often described as a sharp, stabbing sensation that comes and goes.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">Duration</h4>
                        <p class="text-sm text-gray-600">Gas pain usually lasts from a few minutes to a couple of hours. It often improves after passing gas, having a bowel movement, or burping.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">Associated Symptoms</h4>
                        <p class="text-sm text-gray-600">Bloating, abdominal distension, frequent belching or flatulence, relief after passing gas.</p>
                    </div>
                </div>

                <!-- Section 2: Understanding Heart Attack -->
                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-secondary-600 pb-2 mt-8 mb-4">Understanding Heart Attack</h2>

                <p class="text-gray-700 mb-4">
                    A <strong>heart attack</strong> (myocardial infarction) occurs when blood flow to a part of the heart muscle is blocked, usually by a blood clot. Without oxygen-rich blood, the heart muscle begins to die. This is a medical emergency - the longer the blockage remains, the more damage occurs to the heart muscle.
                </p>

                <p class="text-gray-700 mb-6">
                    According to the American Heart Association, someone in the United States has a heart attack every 40 seconds. In India, cardiovascular diseases account for nearly 25% of all deaths. Recognizing the warning signs early can mean the difference between survival and death, or between full recovery and permanent heart damage.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Classic Heart Attack Symptoms</h3>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Chest Discomfort</strong> - Pressure, squeezing, fullness, or pain in the center of the chest lasting more than a few minutes</li>
                    <li><strong>Upper Body Pain</strong> - Discomfort in one or both arms, the back, neck, jaw, or stomach</li>
                    <li><strong>Shortness of Breath</strong> - With or without chest discomfort</li>
                    <li><strong>Cold Sweat</strong> - Breaking out in a cold sweat with no apparent reason</li>
                    <li><strong>Nausea</strong> - Feeling sick to your stomach or vomiting</li>
                    <li><strong>Lightheadedness</strong> - Feeling dizzy or faint</li>
                    <li><strong>Fatigue</strong> - Unusual tiredness, especially in women</li>
                </ul>

                <div class="bg-red-50 border-l-4 border-red-500 p-4 rounded-r-lg mb-6">
                    <strong class="text-red-700">Emergency Signs:</strong>
                    <span class="text-gray-700"> If you experience chest discomfort combined with shortness of breath, pain radiating to the arm/jaw, or cold sweats - call emergency services immediately!</span>
                </div>

