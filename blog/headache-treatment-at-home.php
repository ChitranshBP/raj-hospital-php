                    <li>Stay consistently hydrated through the day.</li>
                    <li>Keep regular meal and sleep times.</li>
                    <li>Take frequent screen breaks and fix your desk posture.</li>
                    <li>Manage stress with exercise, breathing or relaxation.</li>
                    <li>Limit caffeine and alcohol, which can both trigger headaches.</li>
                    <li>Keep a simple headache diary to spot your personal triggers.</li>
