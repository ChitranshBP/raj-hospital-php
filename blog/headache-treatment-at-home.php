                <h2 class="raj-h2"><i data-feather="list" class="raj-h2-icon"></i> 10 Home Remedies for Fast Headache Relief</h2>

                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="droplet" class="raj-icon raj-icon-md raj-icon-secondary"></i> 1. Drink water</h3>
                        <p class="raj-card-body">Dehydration is one of the most common headache triggers. Drink 1–2 glasses of water at the first sign of pain; mild dehydration headaches often ease within 30–60 minutes.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="moon" class="raj-icon raj-icon-md raj-icon-secondary"></i> 2. Rest in a dark, quiet room</h3>
                        <p class="raj-card-body">Lie down away from bright light and noise for 20–30 minutes. This is especially helpful for migraines, which are sensitive to light and sound.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="thermometer" class="raj-icon raj-icon-md raj-icon-secondary"></i> 3. Cold or warm compress</h3>
                        <p class="raj-card-body">A cold pack on the forehead helps migraines; a warm compress on the neck and shoulders eases tension headaches. Use for 10–15 minutes.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="wind" class="raj-icon raj-icon-md raj-icon-secondary"></i> 4. Gentle head &amp; neck massage</h3>
                        <p class="raj-card-body">Massage your temples, the base of the skull and tight neck muscles for a few minutes to release tension and improve blood flow.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="coffee" class="raj-icon raj-icon-md raj-icon-secondary"></i> 5. A little caffeine</h3>
                        <p class="raj-card-body">A small cup of tea or coffee can relieve some headaches and boost painkillers. But don't overdo it — too much caffeine can cause rebound headaches.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="wind" class="raj-icon raj-icon-md raj-icon-secondary"></i> 6. Slow, deep breathing</h3>
                        <p class="raj-card-body">Stress is a major trigger. Try 5 minutes of slow breathing or simple meditation to calm the nervous system and loosen tense muscles.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="clock" class="raj-icon raj-icon-md raj-icon-secondary"></i> 7. Don't skip meals</h3>
                        <p class="raj-card-body">Low blood sugar from skipped or delayed meals commonly triggers headaches. Eat regular, balanced meals and keep a healthy snack handy.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="monitor" class="raj-icon raj-icon-md raj-icon-secondary"></i> 8. Rest your eyes from screens</h3>
                        <p class="raj-card-body">Follow the 20-20-20 rule: every 20 minutes, look 20 feet away for 20 seconds. Correct lighting and posture reduce eye-strain headaches.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="feather" class="raj-icon raj-icon-md raj-icon-secondary"></i> 9. Try ginger or peppermint</h3>
                        <p class="raj-card-body">Ginger tea may ease headache-related nausea, and dabbing diluted peppermint oil on the temples can feel soothing for tension headaches.</p>
                    </div>
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="sunrise" class="raj-icon raj-icon-md raj-icon-secondary"></i> 10. Fix your sleep</h3>
                        <p class="raj-card-body">Both too little and too much sleep trigger headaches. Aim for 7–8 hours on a regular schedule — one of the most powerful long-term remedies.</p>
                    </div>
