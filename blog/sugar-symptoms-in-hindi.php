                        <p class="text-sm text-gray-600">Low glucose से muscles को energy नहीं मिलती, jis se tremors होती हैं।</p>
                    </div>
                    <div class="raj-callout raj-callout-warning">
                        <h4 class="font-bold text-yellow-700">2. Svedaana (Sweating)</h4>
