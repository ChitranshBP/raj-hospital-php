                    </div>
                    <div class="raj-callout raj-callout-danger">
                        <h4 class="font-bold text-red-700">3. Increased Hunger (Bahut bhuk)</h4>
                        <p class="text-sm text-gray-600">Cells glucose use नहीं कर पा रहे, तो body aur energy चाहती है।</p>
