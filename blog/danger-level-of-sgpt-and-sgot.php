                                <td class="border border-gray-300 p-3">Above 500</td>
                            </tr>
                        </tbody>
                    </table>
                </div>

                <p class="text-gray-700 mb-4">
                    Note: Normal ranges may vary slightly between laboratories depending on the testing methods and equipment used. Always consult with your doctor to interpret your specific results.
                </p>

                <!-- Section 3: What Causes Elevated Levels? -->
                <h2 class="raj-h2">What Causes Elevated SGPT and SGOT Levels?</h2>

                <p class="text-gray-700 mb-6">
                    Elevated liver enzymes don't happen in isolation. There are numerous factors that can cause your SGPT and SGOT levels to rise:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Liver Diseases</h4>
                        <p class="text-sm text-gray-600">Hepatitis (A, B, C), fatty liver disease, cirrhosis, and liver cancer can all cause significant elevation in these enzymes.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Alcohol Consumption</h4>
                        <p class="text-sm text-gray-600">Heavy alcohol use damages liver cells, causing both SGPT and SGOT to rise. AST:ALT ratio greater than 2:1 is often a sign of alcoholic liver disease.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Medications</h4>
                        <p class="text-sm text-gray-600">Certain medications like statins, antibiotics, anti-epileptic drugs, and some pain relievers can elevate liver enzymes as a side effect.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Obesity and Metabolic Syndrome</h4>
                        <p class="text-sm text-gray-600">Non-alcoholic fatty liver disease (NAFLD) is strongly associated with obesity, diabetes, and high cholesterol.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">5. Heart Conditions</h4>
                        <p class="text-sm text-gray-600">Heart attack, heart failure, and other cardiac issues can cause SGOT elevation since the enzyme is also found in heart muscles.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">6. Muscle Injuries</h4>
                        <p class="text-sm text-gray-600">Strenuous exercise, trauma, or muscle disorders can elevate SGOT levels.</p>
                    </div>
                </div>

                <!-- Section 4: Danger Levels -->
                <h2 class="raj-h2">When Are SGPT and SGOT Levels Dangerous?</h2>

                <p class="text-gray-700 mb-4">
                    Not all elevated liver enzymes are dangerous. The level of elevation and the pattern of change help doctors determine the severity and cause of the underlying condition.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Mild Elevation (1-3 times normal)</h3>
                <p class="text-gray-700 mb-4">
                    Mild elevations (SGPT: 56-200, SGOT: 40-200) are often seen in:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Fatty liver disease (most common cause)</li>
                    <li>Recent medication use</li>
                    <li>Minor viral infections</li>
                    <li>Recent alcohol consumption</li>
                    <li>Strenuous exercise</li>
                </ul>
                <p class="text-gray-700 mb-6">
                    Mild elevations often resolve on their own with lifestyle changes and don't usually indicate severe liver damage. However, it's important to investigate the cause.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Moderate Elevation (3-10 times normal)</h3>
                <p class="text-gray-700 mb-4">
                    Moderate elevations (SGPT/SGOT between 200-500) may indicate:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Active hepatitis infection</li>
                    <li>Alcoholic hepatitis</li>
                    <li>Drug-induced liver injury</li>
                    <li>Chronic liver disease progression</li>
                </ul>
                <p class="text-gray-700 mb-6">
                    At this level, further testing is usually recommended, including hepatitis screening, imaging studies, and possibly a liver biopsy.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Severe Elevation (Above 10 times normal)</h3>
                <div class="raj-callout raj-callout-danger">
                    <strong class="text-red-700">Critical Warning:</strong>
                    <span class="text-gray-700"> When SGPT or SGOT levels exceed 500 U/L, it indicates significant acute liver injury. This requires immediate medical evaluation and possibly hospitalization.</span>
                </div>
                <p class="text-gray-700 mb-6">
                    Severe elevations can be caused by:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Acute viral hepatitis (especially Hepatitis A or B)</li>
                    <li>Acetaminophen overdose</li>
                    <li>Ischemic hepatitis (shock liver)</li>
                    <li>Autoimmune hepatitis</li>
                    <li>Severe drug reactions</li>
                </ul>

                <!-- Section 5: Symptoms -->
                <h2 class="raj-h2">Signs and Symptoms of Dangerous Liver Enzyme Levels</h2>

                <p class="text-gray-700 mb-4">
                    While elevated liver enzymes are often discovered incidentally during routine blood tests, certain symptoms may indicate significant liver problems:
                </p>

                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Jaundice</strong> - Yellowing of the skin and eyes (indicates bilirubin buildup)</li>
                    <li><strong>Abdominal pain</strong> - Especially in the upper right quadrant where the liver is located</li>
                    <li><strong>Unexplained fatigue</strong> - Persistent tiredness not relieved by rest</li>
                    <li><strong>Nausea and vomiting</strong> - Especially after fatty meals</li>
                    <li><strong>Dark urine</strong> - Urine that appears brown or tea-colored</li>
                    <li><strong>Swelling in abdomen</strong> - Ascites (fluid accumulation)</li>
                    <li><strong>Easy bruising</strong> - Due to reduced production of clotting factors</li>
                    <li><strong>Confusion</strong> - In severe cases, indicating hepatic encephalopathy</li>
                </ul>

                <div class="raj-callout raj-callout-warning">
                    <strong class="text-yellow-700"><i data-feather="alert-triangle" class="raj-icon raj-icon-sm raj-icon-yellow" aria-hidden="true"></i> Emergency Signs:</strong>
                    <span class="text-gray-700"> If you experience severe abdominal pain, vomiting blood, confusion, or jaundice along with elevated liver enzymes, seek immediate medical attention.</span>
                </div>

                <!-- Section 6: Diagnosis -->
                <h2 class="raj-h2">How to Diagnose the Cause of Elevated Liver Enzymes</h2>

                <p class="text-gray-700 mb-4">
                    When elevated SGPT/SGOT levels are detected, your doctor will likely recommend additional tests to determine the underlying cause:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">1. Expanded Liver Function Panel</h4>
                        <p class="text-sm text-gray-600">Includes albumin, bilirubin, alkaline phosphatase (ALP), and gamma-glutamyl transferase (GGT) for a complete picture.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">2. Hepatitis Screening</h4>
                        <p class="text-sm text-gray-600">Blood tests for Hepatitis A, B, and C antibodies and antigens.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">3. Imaging Studies</h4>
                        <p class="text-sm text-gray-600">Abdominal ultrasound to evaluate liver structure, detect fatty liver, gallstones, or tumors.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">4. Autoimmune Markers</h4>
