                <!-- FAQs -->
                <h2 class="raj-h2">FAQs - AIDS Symptoms in Men</h2>

                <div class="space-y-4">
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">Can HIV be transmitted through kissing?</h4>
                        <p class="text-gray-700">No, HIV is not transmitted through casual contact like kissing, hugging, sharing food, or using the same toilet. It requires exchange of certain body fluids (blood, semen, vaginal fluid, breast milk).</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">How long does it take for HIV to become AIDS?</h4>
                        <p class="text-gray-700">Without treatment, it typically takes 10-15 years for HIV to progress to AIDS. With proper antiretroviral therapy (ART), most people with HIV never develop AIDS.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-secondary-600 mb-2">Can someone with HIV have no symptoms?</h4>
                        <p class="text-gray-700">Yes, many people with HIV have no symptoms for years, especially in the early stages. This is why regular testing is important if you're at risk.</p>
