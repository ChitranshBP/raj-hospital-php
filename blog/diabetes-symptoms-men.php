                <!-- Section 1: Understanding Diabetes in Men -->
                <h2 class="raj-h2">Understanding Diabetes in Men</h2>

                <p class="text-gray-700 mb-4">
                    Diabetes occurs when your body either doesn't produce enough insulin or can't effectively use the insulin it produces. Insulin is a hormone that regulates blood sugar levels, allowing glucose to enter cells for energy. When this process fails, glucose builds up in the bloodstream, leading to various health problems.
                </p>

                <p class="text-gray-700 mb-4">
                    Men face unique challenges when it comes to diabetes. Research shows that men tend to develop type 2 diabetes at a lower BMI than women, meaning they might not realize they're at risk simply by looking at their weight. Additionally, men are often less aware of their body changes and may ignore symptoms that women would typically address with a doctor.
                </p>

                <div class="raj-callout raj-callout-info">
                    <strong class="text-blue-700">Key Fact:</strong>
                    <span class="text-gray-700"> Men are 26% more likely to develop type 2 diabetes than women, even after adjusting for BMI. This makes recognizing symptoms even more critical for men's health.</span>
                </div>

                <!-- Section 2: Common Diabetes Symptoms -->
                <h2 class="raj-h2">Common Diabetes Symptoms in Men</h2>

                <p class="text-gray-700 mb-6">
                    The classic symptoms of diabetes in men are similar to those in women, but understanding how they manifest is essential for early detection:
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">1. Frequent Urination (Polyuria)</h3>
                <p class="text-gray-700 mb-4">
                    When blood sugar levels are high, the kidneys work overtime to filter and absorb the excess glucose. This leads to increased urine production, causing you to urinate more frequently, especially during the night (nocturia). For men, this might be mistaken for a prostate issue, making it important to get blood sugar tested.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">2. Excessive Thirst (Polydipsia)</h3>
                <p class="text-gray-700 mb-4">
                    The frequent urination caused by diabetes leads to dehydration, which triggers intense feelings of thirst. Despite drinking more fluids, men might find that their thirst never seems to be quenched. This creates a vicious cycle where more fluid intake leads to more urination.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">3. Increased Hunger (Polyphagia)</h3>
                <p class="text-gray-700 mb-4">
                    Even when eating regular meals, men with diabetes may feel constantly hungry. This happens because the body's cells aren't receiving enough glucose for energy, even though there's plenty of glucose in the bloodstream. The body signals for more food in an attempt to provide fuel.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">4. Unexplained Weight Loss</h3>
                <p class="text-gray-700 mb-4">
                    Rapid, unexplained weight loss is often one of the first noticeable signs of diabetes in men. This occurs because the body starts breaking down muscle and fat for energy when it can't use glucose properly. Despite eating normally or even more than usual, weight continues to drop.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">5. Fatigue and Weakness</h3>
                <p class="text-gray-700 mb-4">
                    Chronic fatigue is one of the most common diabetes symptoms in men. When glucose can't enter cells efficiently, the body lacks the energy it needs to function properly. Men might notice they're unusually tired after meals, struggle to get through the workday, or feel exhausted despite adequate sleep.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">6. Blurred Vision</h3>
                <p class="text-gray-700 mb-4">
                    High blood sugar levels can cause the lens inside the eye to swell, leading to blurred vision. This symptom might come and go as blood sugar levels fluctuate. If left untreated, diabetes can cause permanent vision damage and increase the risk of diabetic retinopathy.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">7. Slow Healing of Cuts and Wounds</h3>
                <p class="text-gray-700 mb-4">
                    Men who notice that even small cuts or bruises take weeks to heal may be experiencing a diabetes symptom. High blood sugar damages blood vessels and affects circulation, reducing the body's ability to heal. This is particularly noticeable on the feet and lower legs.
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">8. Tingling or Numbness in Hands and Feet</h3>
                <p class="text-gray-700 mb-4">
                    Diabetic neuropathy, or nerve damage, often manifests as tingling, numbness, or burning sensations in the hands, fingers, feet, and toes. This typically starts in the extremities and can progressively worsen if blood sugar levels aren't controlled.
                </p>

                <!-- Section 3: Men-Specific Symptoms -->
                <h2 class="raj-h2">Diabetes Symptoms Specific to Men</h2>

                <p class="text-gray-700 mb-4">
                    While many diabetes symptoms are common to both sexes, there are certain symptoms that men specifically experience:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Erectile Dysfunction (ED)</h4>
                        <p class="text-sm text-gray-600">Diabetes is one of the leading causes of erectile dysfunction in men. High blood sugar damages blood vessels and nerves that are essential for achieving and maintaining an erection. Studies show that men with diabetes are 3 times more likely to experience ED than those without the condition. This can be an early warning sign of diabetes or a complication of poorly controlled blood sugar.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Decreased Testosterone Levels</h4>
                        <p class="text-sm text-gray-600">Diabetes significantly impacts testosterone production in men. Studies indicate that men with type 2 diabetes often have lower testosterone levels, which can lead to reduced muscle mass, increased body fat, fatigue, and decreased libido. This creates a dangerous cycle as low testosterone can also contribute to insulin resistance.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Recurrent Fungal Infections</h4>
                        <p class="text-sm text-gray-600">Men with diabetes are more prone to fungal infections, particularly jock itch (tinea cruris) and athlete's foot. These infections thrive in warm, moist areas of the body and can be difficult to treat if blood sugar isn't controlled. Yeast infections under the foreskin (balanitis) are also more common in diabetic men.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Urinary Problems</h4>
                        <p class="text-sm text-gray-600">Diabetes can cause overactive bladder, frequent urination, and difficulty emptying the bladder completely. Men might also experience a weak urine stream or dribbling. These symptoms can be mistaken for prostate issues but may actually be related to diabetic neuropathy affecting bladder function.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Reduced Muscle Mass</h4>
                        <p class="text-sm text-gray-600">High insulin resistance means the body can't properly use glucose for energy, leading to muscle breakdown. Men might notice their arms and legs appearing thinner or feeling weaker during physical activities. This loss of muscle mass further reduces the body's ability to use insulin effectively.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Increased Abdominal Fat</h4>
                        <p class="text-sm text-gray-600">Men are more likely to accumulate fat around the abdomen (visceral fat) when they develop diabetes. This "beer belly" pattern is strongly associated with insulin resistance and metabolic syndrome. Losing abdominal fat is particularly effective at improving insulin sensitivity in men.</p>
                    </div>
                </div>

                <!-- Section 4: Risk Factors -->
                <h2 class="raj-h2">Why Men Are at Higher Risk</h2>

                <p class="text-gray-700 mb-4">
                    Several factors contribute to why men might be at higher risk for developing diabetes:
                </p>

                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Higher average BMI for diagnosis</strong> - Men typically develop type 2 diabetes at a higher BMI than women</li>
                    <li><strong>Less body awareness</strong> - Men are generally less likely to notice or act on subtle symptoms</li>
                    <li><strong>Less frequent doctor visits</strong> - Men visit doctors less often, missing opportunities for early detection</li>
                    <li><strong>Waist circumference</strong> - Men tend to carry weight in the abdomen, which is a significant risk factor</li>
                    <li><strong>Muscle mass</strong> - While more muscle mass is protective, the modern sedentary lifestyle negates this benefit</li>
                    <li><strong>Lifestyle factors</strong> - Higher rates of smoking, alcohol consumption, and poor diet in some populations</li>
                </ul>

