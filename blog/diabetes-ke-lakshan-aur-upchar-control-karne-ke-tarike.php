                    <li><strong>अधिक पेशाब आना (Polyuria)</strong> - बार-बार और अधिक मात्रा में पेशाब आना</li>
                    <li><strong>अधिक भूख लगना (Polyphagia)</strong> - खाने के बाद भी भूख लगना</li>
                    <li><strong>असमान्य थकान</strong> - बिना किसी कारण के थकान महसूस होना</li>
                    <li><strong>वजन घटना</strong> - बिना डाइट या व्यायाम के वजन कम होना (Type 1 में अधिक आम)</li>
                    <li><strong>धुंधली दृष्टि</strong> - आंखों की रोशनी में कमी</li>
                    <li><strong>घाव धीरे ठीक होना</strong> - त्वचा पर कट या घाव भरने में समय लगना</li>
                    <li><strong>फंगल इन्फेक्शन</strong> - यीस्ट इन्फेक्शन (त्वचा, नाभि, योनि में)</li>
                    <li><strong>हाथ-पैर में झनझनाहट</strong> - नसों में क्षति का संकेत</li>
                    <li><strong>त्वचा का काला पड़ना</strong> - गर्दन और बगल में काले धब्बे (Acanthosis Nigricans)</li>
                </ul>

