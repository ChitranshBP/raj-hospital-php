                <!-- Section 1: What is PCOD -->
                <h2 class="raj-h2">What is <a href="/specialties/obstetrics-and-gynaecology.php" class="text-red-600 hover:underline font-semibold">PCOD</a>?</h2>

                <p class="text-gray-700 mb-4">
                    <strong><a href="/specialties/obstetrics-and-gynaecology.php" class="text-red-600 hover:underline font-semibold">PCOD</a> (Polycystic Ovarian Disease)</strong> is a condition where the ovaries contain multiple small cysts due to improper egg maturation. This happens because of hormonal imbalance - particularly elevated androgens (male hormones) and insulin resistance.
                </p>

                <div class="raj-callout raj-callout-info">
                    <strong class="text-blue-700">PCOD vs PCOS:</strong>
                    <span class="text-gray-700"> PCOD is a less severe form while <strong>PCOS (Polycystic Ovarian Syndrome)</strong> is a more serious metabolic disorder. PCOD can often be managed with lifestyle changes, while PCOS may require medication.</span>
                </div>

                <!-- Section 2: Symptoms -->
                <h2 class="raj-h2">PCOD Symptoms in Women</h2>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Irregular Periods</h4>
                        <p class="text-sm text-gray-600">Delayed periods, missed periods, or very light/heavy bleeding. Cycles may be longer than 35 days.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Excess Androgens</h4>
                        <p class="text-sm text-gray-600">Elevated male hormones cause hirsutism (excess hair on face, chest, back), acne, and male-pattern baldness.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Weight Gain</h4>
                        <p class="text-sm text-gray-600">Difficulty losing weight, especially around the waist. About 50-70% of women with PCOD are overweight.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Polycystic Ovaries</h4>
                        <p class="text-sm text-gray-600">Ovaries appear enlarged with multiple small follicles (cysts) visible on ultrasound.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">5. Skin Changes</h4>
                        <p class="text-sm text-gray-600">Dark patches (acanthosis nigricans) on neck, groin, underarms due to insulin resistance.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">6. Mood Changes</h4>
                        <p class="text-sm text-gray-600">Depression, anxiety, and mood swings due to hormonal fluctuations.</p>
                    </div>
                </div>

                <!-- Section 3: Causes -->
                <h2 class="raj-h2">PCOD Causes and Risk Factors</h2>

                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Genetics</strong> - Family history of PCOD/PCOS increases risk significantly</li>
                    <li><strong>Insulin Resistance</strong> - About 70% of women with PCOD have insulin resistance</li>
                    <li><strong>Obesity</strong> - Excess weight contributes to hormonal imbalance</li>
                    <li><strong>Sedentary Lifestyle</strong> - Lack of physical activity worsens symptoms</li>
                    <li><strong>Inflammation</strong> - Low-grade chronic inflammation triggers androgen production</li>
                    <li><strong>Poor Diet</strong> - High glycemic index foods worsen insulin resistance</li>
                </ul>

                <!-- Section 4: Health Effects -->
                <h2 class="raj-h2">Health Effects of PCOD</h2>

                <p class="text-gray-700 mb-4">
                    If left untreated, <strong>PCOD can lead to several serious health complications</strong>:
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-red-50 p-4 rounded-lg">
                        <div class="font-bold text-red-700 mb-2">Fertility Issues</div>
                        <p class="text-sm text-gray-600">Irregular ovulation leads to difficulty conceiving. PCOD is one of the leading causes of infertility.</p>
                    </div>
                    <div class="bg-red-50 p-4 rounded-lg">
                        <div class="font-bold text-red-700 mb-2">Type 2 Diabetes</div>
                        <p class="text-sm text-gray-600">Insulin resistance significantly increases the risk of developing type 2 diabetes.</p>
                    </div>
                    <div class="bg-red-50 p-4 rounded-lg">
                        <div class="font-bold text-red-700 mb-2">Heart Disease</div>
                        <p class="text-sm text-gray-600">Increased risk of high blood pressure, high cholesterol, and cardiovascular problems.</p>
                    </div>
                    <div class="bg-red-50 p-4 rounded-lg">
                        <div class="font-bold text-red-700 mb-2">Endometrial Cancer</div>
                        <p class="text-sm text-gray-600">Irregular periods can lead to thickened endometrial lining, increasing cancer risk.</p>
                    </div>
                </div>

                <!-- Section 5: Treatment -->
                <h2 class="raj-h2">PCOD Treatment and Management</h2>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-green-50 p-4 rounded-lg">
                        <div class="font-bold text-green-700 mb-2">Lifestyle Changes</div>
                        <ul class="text-sm text-gray-600 space-y-1">
                            <li>5-10% weight loss can restore hormones</li>
                            <li>Low glycemic diet</li>
                            <li>Regular exercise (30 mins/day)</li>
                            <li>Stress management</li>
                            <li>Adequate sleep (7-8 hours)</li>
                        </ul>
