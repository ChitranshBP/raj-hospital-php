                <h2 class="raj-h2">What Happens to Your Heart During Anxiety or a Panic Attack?</h2>
                <p class="text-gray-700 mb-4">
                    When the brain perceives threat, the amygdala fires the <strong>fight-or-flight response</strong>. The sympathetic nervous system releases adrenaline and cortisol. Within seconds, heart rate climbs to 100–160 bpm, blood pressure spikes, breathing becomes shallow, and pupils dilate. These are the same physical changes that helped our ancestors survive predators — but in modern life, the same response is repeatedly triggered by emails, deadlines, financial worry, and chronic stress.
                </p>
                <p class="text-gray-700 mb-4">
                    In a healthy heart, these episodes are <strong>reversible</strong>. The moment the perceived threat passes, the parasympathetic nervous system brings heart rate and blood pressure back to baseline. The chest tightness, the "skipped beats," and the sense of impending doom — all symptoms — fade. <em>This is the key distinction from a true heart attack, which involves permanent damage to heart muscle from blocked blood flow.</em>
                </p>

                <h2 class="raj-h2">How Chronic Anxiety Raises Heart Attack Risk</h2>
                <p class="text-gray-700 mb-4">
                    The danger is not a single panic attack — it is the cumulative effect of years of elevated stress hormones. A 2023 meta-analysis in the journal <em>Circulation</em> followed 220,000 adults for 11 years and found that people with generalized anxiety disorder had a <strong>34% higher risk of cardiovascular events</strong> and a <strong>41% higher risk of coronary heart disease</strong> than matched controls. The mechanisms are well understood:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Sustained high blood pressure</strong> damages arterial walls and accelerates atherosclerosis.</li>
                    <li><strong>Chronic systemic inflammation</strong> — measured by elevated CRP and IL-6 — destabilizes plaque in coronary arteries.</li>
                    <li><strong>Unhealthy coping</strong> — many anxious patients smoke, drink alcohol, overeat, or sleep poorly, compounding risk.</li>
                    <li><strong>Endothelial dysfunction</strong> — cortisol reduces the blood vessels' ability to dilate, raising the risk of a clot.</li>
                </ul>

                <h2 class="raj-h2">Stress Cardiomyopathy (Broken Heart Syndrome) — When Anxiety Mimics a Heart Attack</h2>
                <p class="text-gray-700 mb-4">
                    In rare but well-documented cases, an acute surge of stress hormones — triggered by grief, terror, or even a surprise — can cause a temporary ballooning of the left ventricle. This condition, called <strong>Takotsubo cardiomyopathy</strong> or <strong>broken heart syndrome</strong>, presents exactly like a heart attack: crushing chest pain, ECG changes, raised troponin levels. The difference: coronary arteries are clear on angiography, and most patients recover fully within 2–4 weeks with supportive care.
                </p>
                <p class="text-gray-700 mb-4">
                    A Johns Hopkins study published in the <em>Journal of the American Heart Association</em> in 2024 noted that 89% of broken-heart-syndrome cases occur in women, usually post-menopausal, and that 1 in 5 cases are precipitated by an emotional rather than physical trigger. RAJ Hospital's cardiology team in Ranchi is equipped with cardiac MRI and coronary angiography to differentiate broken heart syndrome from a true myocardial infarction within hours.
                </p>

