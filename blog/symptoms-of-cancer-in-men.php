                <p class="text-gray-700 mb-4">
                    Screening looks for cancer before symptoms appear. Age, family history, and personal risk factors guide what is recommended. The following is a general framework; individual plans should be discussed with a doctor.
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Ages 20-39</h4>
                        <p class="text-sm text-gray-600">Monthly testicular self-exam, skin self-checks, annual physicals, and discussion of family history with the doctor.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Ages 40-49</h4>
                        <p class="text-sm text-gray-600">Begin discussions about colorectal screening (especially with family history), blood pressure, cholesterol, blood sugar, and skin checks with a dermatologist if risk factors exist.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Ages 50 and Above</h4>
                        <p class="text-sm text-gray-600">PSA discussions and digital rectal exam for prostate health, colonoscopy or stool-based tests for colorectal cancer, low-dose CT for long-term smokers, and continued skin and testicular checks.</p>
                    </div>
