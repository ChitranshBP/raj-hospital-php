                <!-- Section 2: General warning signs -->
                <h2 class="raj-h2">General Warning Signs That Should Not Be Ignored</h2>

                <p class="text-gray-700 mb-4">
                    While symptoms vary by cancer type, the body often sends warning signals weeks or months before diagnosis. Men should pay close attention to the following changes that last more than two to three weeks.
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Unexplained Weight Loss</h4>
                        <p class="text-sm text-gray-600">Losing more than 5 kg (10 pounds) without changes in diet or activity warrants evaluation. It is one of the classic warning signs of cancers of the pancreas, stomach, esophagus, or lung.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Persistent Fatigue</h4>
                        <p class="text-sm text-gray-600">Tiredness that does not improve with rest can signal blood cancers (leukemia, lymphoma), colon cancer, or advanced disease in many tumor types.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Lumps or Masses</h4>
                        <p class="text-sm text-gray-600">A new lump under the skin, in the testicle, breast tissue, neck, groin, or armpit should never be ignored, even if it is painless.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Skin Changes</h4>
                        <p class="text-sm text-gray-600">Moles that change in size, shape, or color, non-healing sores, yellowing of skin (jaundice), or unusual darkening may point to skin, liver, or pancreatic cancers.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">5. Persistent Pain</h4>
                        <p class="text-sm text-gray-600">Pain that does not improve with rest or medication, especially headaches, back pain, or bone pain, can be an early signal of brain, bone, or prostate cancer.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">6. Changes in Bowel or Bladder Habits</h4>
                        <p class="text-sm text-gray-600">Blood in stool, persistent constipation or diarrhea, change in stool caliber, blood in urine, or difficulty urinating can indicate colorectal, bladder, or prostate cancers.</p>
                    </div>
                </div>

