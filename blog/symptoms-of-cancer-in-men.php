                <h2 class="raj-h2">When to See a Doctor</h2>

                <p class="text-gray-700 mb-4">
                    Any new, persistent, or worsening symptom that lasts more than two to three weeks should be reviewed. Specific situations that need prompt medical attention include:
                </p>

                <ul class="list-disc pl-6 mb-6 text-gray-700 space-y-1">
                    <li>Unexplained weight loss or persistent fatigue.</li>
                    <li>A new lump, swelling, or mass anywhere in the body.</li>
                    <li>Blood in urine, stool, vomit, or coughed up from the lungs.</li>
                    <li>Persistent cough, hoarseness, or difficulty swallowing.</li>
                    <li>Non-healing sores or changes in a mole.</li>
                    <li>Severe pain that does not respond to usual treatment.</li>
                </ul>

                <p class="text-gray-700 mb-4">
                    Timely consultation allows doctors to use blood tests, imaging, biopsies, and specialist referrals to confirm or rule out cancer. Even when cancer is not the cause, the underlying condition still needs treatment.
                </p>

