                <h2 class="raj-h2"><i data-feather="activity" class="raj-h2-icon"></i> Sinus Headache vs Migraine — Getting the Diagnosis Right</h2>
                <p class="text-gray-700 mb-4">
                    This is the single most important part of "curing" a sinus headache. Research has repeatedly found that a large share of people who think they have sinus headaches actually have <strong>migraines</strong> — which explains why decongestants and antibiotics don't help them. The two need very different treatment.
                </p>
                <div class="raj-grid">
                    <div class="raj-card">
                        <h3 class="raj-card-title"><i data-feather="wind" class="raj-icon raj-icon-md raj-icon-secondary"></i> More likely a sinus headache</h3>
                        <ul class="list-disc list-inside text-sm space-y-1 text-gray-700">
                            <li>Followed a cold or allergy flare-up</li>
                            <li>Blocked nose with thick/discoloured mucus</li>
                            <li>Pressure over forehead, cheeks, nose bridge</li>
                            <li>Worse bending forward; sometimes fever</li>
                            <li>Reduced sense of smell</li>
