                        <h4 class="font-bold text-primary-600">1. Enlarged Prostate (BPH)</h4>
                        <p class="text-sm text-gray-600">50+ age में prostate बड़ा होना common है। यह bladder को completely empty करने में problem करता है, जिससे bacteria grow करती हैं।</p>
