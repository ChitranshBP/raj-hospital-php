                <h2 class="raj-h2-secondary">पुरुषों में UTI के लक्षण (Symptoms)</h2>

                <div class="bg-blue-50 border-l-4 border-primary-600 p-4 rounded-r-lg mb-6">
                    <h4 class="font-bold text-primary-600 mb-2">Primary Symptoms (मुख्य लक्षण):</h4>
                    <ul class="text-gray-700 space-y-2">
                        <li><strong>1. Dysuria (पेशाब में जलन)</strong> - पेशाब करते समय जलन या दर्द। यह सबसे common और prominent symptom है।</li>
                        <li><strong>2. बार-बार पेशाब (Frequency)</strong> - पेशाब की urgent feeling, हर कुछ मिनट में जाने का मन। लेकिन हर बार कम quantity आती है।</li>
                        <li><strong>3. Nocturia (रात को उठकर पेशाब)</strong> - रात को कई बार पेशाब के लिए उठना। sleep में बाधा।</li>
                        <li><strong>4. Hematuria (पेशाब में खून)</strong> - पेशाब में खून दिखना। urine pink या reddish हो सकता है।</li>
                        <li><strong>5. suprapubic Pain (नीचे पेट में दर्द)</strong> - जघन क्षेत्र (lower abdomen) में दर्द या pressure sensation।</li>
                        <li><strong>6. Cloudy या foul-smelling urine</strong> - पेशाब का रंग बदलना और बदबू आना।</li>
                    </ul>
                </div>

