                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">3. Improper Hygiene</h4>
                        <p class="text-sm text-gray-600">Genital area की improper cleaning से bacteria spread हो सकती हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">4. Unprotected Sexual Activity</h4>
                        <p class="text-sm text-gray-600">Sexual intercourse के through bacteria urinary tract में enter कर सकते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">5. Diabetes</h4>
                        <p class="text-sm text-gray-600">High blood sugar immune system को weak करती है और bacteria growth को promote करती है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">6. Urinary Catheter</h4>
