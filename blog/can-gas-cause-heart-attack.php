                <h2 class="raj-h2">The 4 Common Conditions That Confuse Patients</h2>
                <p class="text-gray-700 mb-4">
                    In the cardiology OPD at <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">RAJ Hospital Ranchi</a>, four non-cardiac conditions account for most "I thought I was having a heart attack" presentations:
                </p>
                <ol class="list-decimal list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Gastro-oesophageal reflux disease (GERD)</strong> — stomach acid backflows into the oesophagus, producing a burning chest pain that mimics angina. Endoscopy confirms it.</li>
                    <li><strong>Hiatus hernia</strong> — part of the stomach pushes up into the chest cavity, causing post-meal chest tightness and breathlessness.</li>
                    <li><strong>Splenic flexure syndrome</strong> — gas trapped in the splenic flexure of the colon produces pain in the left upper abdomen radiating to the left shoulder — the classic "gas mimic of heart attack."</li>
                    <li><strong>Gallbladder disease (cholelithiasis)</strong> — biliary colic is felt in the right upper abdomen and right shoulder, but can produce central chest tightness in some patients.</li>
                </ol>

                <h2 class="raj-h2">What Tests Distinguish Gas From Heart Attack?</h2>
                <p class="text-gray-700 mb-4">
                    The emergency and cardiology team at <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">RAJ Hospital, the best multispeciality hospital in Ranchi</a>, follows a structured chest-pain protocol that is completed in under 30 minutes:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>12-lead ECG</strong> — checks for ST-segment elevation/depression. A normal ECG during pain is reassuring.</li>
                    <li><strong>High-sensitivity troponin (hs-cTnI)</strong> — a negative test 1 hour and 3 hours after pain onset essentially rules out a heart attack.</li>
                    <li><strong>Chest X-ray</strong> — checks for pneumothorax, large hiatal hernia, or lung cause.</li>
                    <li><strong>Upper GI endoscopy</strong> — for suspected GERD, ulcer, or hiatus hernia.</li>
                    <li><strong>2D echocardiography</strong> — assesses heart wall motion; regional wall motion abnormality suggests cardiac cause.</li>
                    <li><strong>Treadmill stress test / CT coronary angiography</strong> — for intermediate-risk patients with normal resting ECG and troponin.</li>
                </ul>

                <h2 class="raj-h2">How to Reduce Gas and Protect Your Heart at the Same Time</h2>
                <p class="text-gray-700 mb-4">
                    Lifestyle changes that reduce gas — small frequent meals, low-FODMAP diet, avoiding carbonated drinks, chewing slowly — also happen to be the cornerstone of <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">preventive cardiology at RAJ Hospital</a>. The big four:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Eat slowly, chew well</strong> — reduces swallowed air, the most common cause of upper abdominal gas.</li>
                    <li><strong>Limit fermented milk, beans, cabbage, onion, and carbonated drinks</strong> — high-FODMAP foods that ferment in the colon.</li>
                    <li><strong>Walk 10–15 minutes after meals</strong> — improves gastric emptying and reduces postprandial angina.</li>
                    <li><strong>Maintain a healthy weight</strong> — central obesity raises both GERD and coronary risk.</li>
                </ul>

