                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-primary-600 pb-2 mt-8 mb-4">प्रसव पीड़ा (Labour Pain) क्या है?</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Labour pain</strong> वह दर्द है जो बच्चे के जन्म देने की प्रक्रिया में होता है। यह दर्द uterus (गर्भाशय) की contractions से होता है जो cervix (गर्भाशय ग्रीवा) को खोलने और baby को बाहर निकालने के लिए होती है।
                </p>

                <p class="text-gray-700 mb-4">
                    प्रसव की प्रक्रिया तीन stages में होती है:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 mb-2">Stage 1: Early Labour (Latent Phase)</h4>
                        <p class="text-sm text-gray-600">Cervix gradually dilate होती है (0-3 cm)। contractions mild से moderate होते हैं। यह stage 6-12 hours तक रह सकती है। contractions irregular हो सकते हैं initially।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 mb-2">Stage 1: Active Labour</h4>
                        <p class="text-sm text-gray-600">Cervix rapid dilate होती है (3-7 cm)। contractions stronger और regular होते हैं। यह stage 4-8 hours रहती है। contractions हर 3-5 minutes के बीच आते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 mb-2">Stage 2: Pushing और Delivery</h4>
                        <p class="text-sm text-gray-600">Cervix fully dilated (10 cm)। baby birth के लिए तैयार। आपको pushing sensation होगा। यह stage 1-2 hours तक रहती है (first-time moms में ज्यादा)।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 mb-2">Stage 3: Placental Delivery</h4>
                        <p class="text-sm text-gray-600">Placenta (आंत) निकलने की प्रक्रिया। यह 5-30 minutes में हो जाती है। generally कम painful होती है।</p>
                    </div>
                </div>

                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-primary-600 pb-2 mt-8 mb-4">असली vs झूठी प्रसव पीड़ा (True vs False Labour)</h2>

                <p class="text-gray-700 mb-4">
                    यह पहचानना important है कि आपकी <strong>pain real labour</strong> है या <strong>Braxton Hicks contractions</strong> (झूठी पीड़ा):
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-green-50 p-4 rounded-lg border-l-4 border-green-600">
                        <h4 class="font-bold text-green-700 mb-2">असली प्रसव पीड़ा (True Labour)</h4>
                        <ul class="text-sm text-gray-600 space-y-1">
                            <li>• Contractions नियमित और predictable</li>
                            <li>• Time के साथ stronger और frequent</li>
                            <li>• दर्द बढ़ता जाता है</li>
                            <li>• Position change से कम नहीं होती</li>
                            <li>• आराम से कम नहीं होती</li>
                            <li>• Lower back pain के साथ</li>
                            <li>• cervix dilate करती है</li>
                        </ul>
                    </div>
                    <div class="bg-red-50 p-4 rounded-lg border-l-4 border-red-500">
                        <h4 class="font-bold text-red-700 mb-2">झूठी प्रसव पीड़ा (False Labour/Braxton Hicks)</h4>
                        <ul class="text-sm text-gray-600 space-y-1">
                            <li>• Contractions irregular</li>
                            <li>• intensity में नहीं बढ़ती</li>
                            <li>• दर्द constant नहीं</li>
                            <li>• Walking से कम हो सकती</li>
                            <li>• Shower या rest से relieved</li>
                            <li>• शुद्ध lower abdomen में</li>
                            <li>• cervix पर कोई effect नहीं</li>
                        </ul>
                    </div>
                </div>

                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-primary-600 pb-2 mt-8 mb-4">प्रसव पीड़ा के लक्षण (Labour Pain Symptoms)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Labour pain ke lakshan</strong> महिला से महिला में अलग हो सकते हैं, लेकिन कुछ common symptoms जो大多数 women experience करती हैं:
                </p>

                <div class="bg-blue-50 border-l-4 border-primary-600 p-4 rounded-r-lg mb-6">
                    <h4 class="font-bold text-primary-600 mb-2">प्रमुख लक्षण (Primary Symptoms):</h4>
                    <ul class="text-gray-700 space-y-2">
                        <li><strong>1. Contractions (संकुचन)</strong> - Uterus की tightening जो regular intervals पर होती है। दर्द wave-like होता है - शुरू होता है, peak होता है, और कम होता है।</li>
                        <li><strong>2. Lower Back Pain (कमर दर्द)</strong> - कई women को contraction के साथ lower back में तेज दर्द होता है। यह "back labour" कहलाता है।</li>
                        <li><strong>3. Bloody Show (रक्तस्त्राव)</strong> - Mucous plug का निकलना जो cervix को seal किए रखता था। गुलाबी या brownish discharge दिख सकता है।</li>
                        <li><strong>4. Amniotic Fluid का टूटना (Water Breaking)</strong> - membranes का टूटना। यह एक sudden gush या continuous leaking के रूप में हो सकता है।</li>
                        <li><strong>5. Feeling of Pressure</strong> - Baby pelvis में नीचे आने का sensation। आपको bathroom जाने का urge बढ़ सकता है।</li>
                    </ul>
                </div>

                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-primary-600 pb-2 mt-8 mb-4">प्रसव के अन्य संकेत (Other Signs of Labour)</h2>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
