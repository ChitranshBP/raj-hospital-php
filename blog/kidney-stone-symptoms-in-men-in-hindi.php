                        <p class="text-sm text-gray-600">High purine diet, gout, या acidic urine से बनती हैं। Protein-rich diet और dehydration से risk बढ़ता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
