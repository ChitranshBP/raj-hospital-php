                        <li><strong>4. बार-बार पेशाब (Frequent Urination)</strong> - पेशाब की urgent feeling, लेकिन हर बार कम quantity आना।</li>
                        <li><strong>5. मतली और उल्टी (Nausea and Vomiting)</strong> - तेज दर्द के कारण या kidney के directly affecting।</li>
