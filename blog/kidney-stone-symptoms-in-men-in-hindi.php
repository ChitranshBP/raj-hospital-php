                    <strong>Kidney stone symptoms in men</strong> size, location, और type पर depend करते हैं। कई बार छोटी stones बिना symptoms के भी निकल सकती हैं, लेकिन बड़ी stones गंभीर problems कर सकती हैं।
                </p>

                <div class="bg-blue-50 border-l-4 border-primary-600 p-4 rounded-r-lg mb-6">
                    <h4 class="font-bold text-primary-600 mb-2">Primary Symptoms (मुख्य लक्षण):</h4>
                    <ul class="text-gray-700 space-y-2">
                        <li><strong>1. तेज पीठ दर्द (Severe Back Pain)</strong> - सबसे characteristic symptom। दर्द usually पसलियों के नीचे से शुरू होकर groin तक फैलता है। यह waves में आता है और बहुत तेज हो सकता है।</li>
