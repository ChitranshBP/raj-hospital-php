                <h2 class="raj-h2-secondary">पथरी के कारण (Causes)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Kidney stone causes</strong> में multiple factors शामिल हैं:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">1. Dehydration</h4>
                        <p class="text-sm text-gray-600">पानी की कमी से urine में minerals concentration बढ़ता है, जो stones बनने का risk increase करता है। गर्म climate में काम करने वालों और athletes में ज्यादा risk है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">2. Diet</h4>
                        <p class="text-sm text-gray-600">High oxalate foods (spinach, rhubarb, nuts, chocolate), high protein diet, excessive sodium, और processed foods से risk बढ़ता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">3. Obesity</h4>
                        <p class="text-sm text-gray-600">Obesity insulin resistance और urinary chemistry को बदलता है, जो stones formation को promote करता है। Weight loss से risk कम हो सकती है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">4. Family History</h4>
                        <p class="text-sm text-gray-600">अगर परिवार में किसी को पथरी है, तो आपको भी होने का risk ज्यादा है। Genetic factors important role play करते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600">5. Medical Conditions</h4>
                        <p class="text-sm text-gray-600">Gout, hyperparathyroidism, urinary tract infections, inflammatory bowel disease, और कुछ metabolic disorders से risk बढ़ता है।</p>
                    </div>
                </div>

                <h2 class="raj-h2-secondary">पथरी का Diagnosis</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Kidney stone diagnosis</strong> के लिए कई tests किए जाते हैं:
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">1. Blood Tests</h4>
                        <p class="text-sm text-gray-600">Calcium, uric acid, और kidney function की जांच। यह underlying conditions detect करने में help करती है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">2. Urine Tests</h4>
                        <p class="text-sm text-gray-600">24-hour urine collection test। यह urine chemistry analyze करता है और recurrence risk assess करता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">3. Imaging Tests</h4>
                        <p class="text-sm text-gray-600">CT scan (gold standard), X-ray, और ultrasound। ये stones की size, location, और number बताते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">4. Stone Analysis</h4>
                        <p class="text-sm text-gray-600">अगर पथरी निकल जाए, तो उसका analysis करवाना useful है। यह भविष्य में recurrence prevent करने में help करता है।</p>
                    </div>
                </div>

                <h2 class="raj-h2-secondary">पथरी का इलाज (Treatment)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Kidney stone treatment</strong> stone की size और type पर depend करता है:
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">1. छोटी पथरी के लिए (Conservative Treatment)</h3>
                <div class="bg-blue-50 p-4 rounded-lg mb-6">
                    <ul class="text-gray-700 space-y-2">
                        <li><strong>Pain Management:</strong> NSAIDs (ibuprofen, naproxen) या prescribed painkillers</li>
                        <li><strong>Medical Expulsion Therapy:</strong> Alpha blockers (जैसे tamsulosin) जो ureter को relax करते हैं और stone pass होने में मदद करते हैं</li>
                        <li><strong>Hydration:</strong> ज्यादा पानी पीना (3-4 liters/day)</li>
                        <li><strong>Watchful Waiting:</strong> अगर stone <5mm है, तो 4-6 weeks में self-pass हो सकती है</li>
                    </ul>
                </div>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">2. बड़ी पथरी के लिए (Surgical/Procedural Treatment)</h3>
                <div class="bg-blue-50 p-4 rounded-lg mb-6">
                    <ul class="text-gray-700 space-y-2">
                        <li><strong>ESWL (Extracorporeal Shock Wave Lithotripsy):</strong> बाहर से shock waves से stone को तोड़ना। 1-2cm तक की stones के लिए।</li>
                        <li><strong>Ureteroscopy:</strong> ureter के through camera और laser डालकर stone निकालना। Especially lower ureter stones के लिए।</li>
                        <li><strong>PCNL (Percutaneous Nephrolithotomy):</strong> बड़ी stones (>2cm) के लिए, kidney में छोटा incision करके directly stone निकालना।</li>
                        <li><strong>Open Surgery:</strong> आजकल rare, सिर्फ very large या complex stones के लिए।</li>
                    </ul>
                </div>

