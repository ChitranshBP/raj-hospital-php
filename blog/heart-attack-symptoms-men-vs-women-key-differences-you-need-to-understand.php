                        <h4 class="font-bold text-primary-500">Hormonal Differences</h4>
                        <p class="text-sm text-gray-600">Estrogen provides some protective effects for women's hearts before menopause. After menopause, women's heart attack risk increases significantly. The hormonal influence affects how pain signals are processed and perceived.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-500">
                        <h4 class="font-bold text-primary-500">Heart Size and Structure</h4>
                        <p class="text-sm text-gray-600">Women's hearts and coronary arteries are typically smaller than men's. This anatomical difference can affect how blockages develop and present symptoms.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-500">
                        <h4 class="font-bold text-primary-500">Type of Blockage</h4>
                        <p class="text-sm text-gray-600">Men more commonly experience blockages in the major coronary arteries, causing typical chest pain symptoms. Women may have blockages in smaller arteries or microvascular disease, leading to subtler symptoms.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-primary-500">
                        <h4 class="font-bold text-primary-500">Pain Perception</h4>
                        <p class="text-sm text-gray-600">Studies suggest women may have different pain perception and thresholds, leading to more diffuse or ambiguous symptoms that are harder to connect with heart problems.</p>
                    </div>
