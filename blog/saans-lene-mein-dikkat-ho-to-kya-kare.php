                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Arrhythmia</h4>
                        <p class="text-sm text-gray-600">Irregular heart rhythm से भी breathing difficulty हो सकती है।</p>
