                <h2 id="components" class="text-2xl font-bold text-gray-800 mb-4">
                    KFT Test Ke Components - What Parameters Are Tested
                </h2>
                <p class="text-gray-600 mb-4">
                    <strong>KFT test</strong> में कई important parameters check होते हैं। आइए विस्तार से जानते हैं <strong>KFT test kya hota hai</strong> के हर component के बारे में:
                </p>

                <div class="space-y-4">
                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">1. Serum Creatinine</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            Creatinine एक waste product है जो muscles से बनता है। जब kidney सही से काम नहीं करते, creatinine खून में accumulate हो जाता है। <strong>High creatinine level</strong> kidney problem का sign हो सकता है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> 0.7-1.3 mg/dL (men), 0.6-1.1 mg/dL (women)</span>
                        </div>
                    </div>

                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">2. Blood Urea Nitrogen (BUN)</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            <strong>BUN</strong> protein metabolism का waste product है जो liver से बनता है और kidney बाहर निकालते हैं। BUN की level kidney function aur hydration status दोनों को reflect करती है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> 7-20 mg/dL</span>
                        </div>
                    </div>

                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">3. Glomerular Filtration Rate (GFR)</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            <strong>GFR</strong> सबसे important parameter है। यह बताता है कि kidney प्रति minute कितना blood filter करती है। <strong>GFR value</strong> kidney function की overall picture देता है। Age के साथ GFR naturally कम होता है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> 90-120 mL/min/1.73m²</span>
                        </div>
                    </div>

                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">4. Uric Acid</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            <strong>Uric acid</strong> purines (जो कुछ foods में होते हैं) से बनता है। High uric acid <strong>gout</strong> और kidney stones का कारण बन सकता है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> 3.5-7.2 mg/dL (men), 2.5-6.0 mg/dL (women)</span>
                        </div>
                    </div>

                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">5. Electrolytes (Sodium, Potassium, Chloride)</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            <strong>Electrolytes</strong> body ke fluid balance aur nerve/muscle function के लिए important hain। Kidney इलेक्ट्रोलाइट्स को regulate करते हैं। <strong>Kidney dysfunction</strong> से electrolytes में imbalance हो सकता है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> Sodium: 136-145 mEq/L, Potassium: 3.5-5.0 mEq/L, Chloride: 98-106 mEq/L</span>
                        </div>
                    </div>

                    <div class="bg-white border rounded-xl p-6 shadow-sm">
                        <h3 class="font-semibold text-gray-800 mb-2 text-xl">6. Blood Urea (Urea)</h3>
                        <p class="text-gray-600 text-sm mb-2">
                            <strong>Urea</strong> protein breakdown का waste product है। BUN के साथ मिलकर urea भी kidney function assess करने में मदद करता है।
                        </p>
                        <div class="bg-green-50 p-3 rounded-lg">
                            <span class="text-sm"><strong>Normal Range:</strong> 10-40 mg/dL</span>
                        </div>
                    </div>
                </div>
            </section>

