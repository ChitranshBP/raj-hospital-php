                <h2 class="raj-h2-secondary">थायरॉइड की जांच (Diagnosis)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Thyroid diagnosis</strong> primarily blood tests पर based है:
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">TSH (Thyroid Stimulating Hormone)</h4>
                        <p class="text-sm text-gray-600">यह primary screening test है। Normal range: 0.4-4.0 mIU/L। High TSH = hypothyroidism, Low TSH = hyperthyroidism।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">T4 (Thyroxine) Test</h4>
                        <p class="text-sm text-gray-600">Free T4 levels check करता है। Low T4 + High TSH = hypothyroidism। High T4 + Low TSH = hyperthyroidism।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">T3 Test</h4>
                        <p class="text-sm text-gray-600">T3 levels check करता है। Hyperthyroidism diagnosis में helpful, especially T3 toxicosis में।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg">
                        <h4 class="font-bold text-primary-600 mb-2">Thyroid Antibody Tests</h4>
                        <p class="text-sm text-gray-600">TPO antibodies और Thyroglobulin antibodies। Autoimmune thyroiditis (Hashimoto's, Graves') detect करने में helpful।</p>
