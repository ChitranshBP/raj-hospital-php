            <p>क्या आपको <strong>थकान और कमजोरी</strong> महसूस होती है? क्या आपका चेहरा <strong>पीला पड़</strong> गया है? हो सकता है कि आपका <strong>हीमोग्लोबिन (Haemoglobin)</strong> स्तर कम हो गया हो। हीमोग्लोबिन शरीर में ऑक्सीजन परिवहन का मुख्य कार्य करता है, और इसके कम होने से कई स्वास्थ्य समस्याएं हो सकती हैं।</p>

            <p>इस लेख में हम विस्तार से जानेंगे कि <strong>हीमोग्लोबिन क्या होता है</strong>, इसके सामान्य स्तर, कम या ज्यादा होने के कारण और लक्षण, और इससे बचाव के उपाय। साथ ही, हम बात करेंगे कि <strong>रांची में हीमोग्लोबिन की जांच</strong> कहां और कैसे करवाएं।</p>

            <!-- Section 1: What is Haemoglobin -->
            <h2>हीमोग्लोबिन (Haemoglobin) क्या है?</h2>

            <p><strong>हीमोग्लोबिन (Haemoglobin)</strong> एक विशेष प्रकार का प्रोटीन है जो हमारे रक्त की <strong>लाल रक्त कणिकाओं (Red Blood Cells या RBCs)</strong> में पाया जाता है। इसका रंग लाल होता है क्योंकि इसमें <strong>आयरन (Iron)</strong> होता है।</p>

            <p>हीमोग्लोबिन का मुख्य कार्य शरीर के विभिन्न हिस्सों तक <strong>ऑक्सीजन पहुंचाना</strong> है। यह फेफड़ों से ऑक्सीजन लेकर रक्त के जरिए पूरे शरीर में पहुंचाता है। साथ ही, यह कार्बन डाइऑक्साइड (CO2) को भी फेफड़ों तक वापस ले जाता है जहां से यह बाहर निकाल दी जाती है।</p>

            <div class="highlight-box">
                <strong>महत्वपूर्ण तथ्य:</strong> एक स्वस्थ वयस्क के शरीर में प्रत्येक मिलीलीटर रक्त में लगभग <strong>15 ग्राम डेसीलीटर (g/dL)</strong> हीमोग्लोबिन होता है। यह लाल रक्त कणिकाओं में मौजूद होता है और शरीर की कुल रक्त आपूर्ति का एक महत्वपूर्ण हिस्सा है।
            </div>

            <h3>हीमोग्लोबिन का वैज्ञानिक संरचना और कार्य:</h3>

            <p>हीमोग्लोबिन एक <strong>चतुष्क प्रोटीन (quaternary protein)</strong> है जिसमें चार प्रोटीन सबयूनिट्स होते हैं। प्रत्येक सबयूनिट में एक <strong>हेम (heme)</strong> समूह होता है जिसके केंद्र में <strong>आयरन का परमाणु</strong> होता है। यही आयरन ऑक्सीजन को बांधता है और शरीर में परिवहन करता है।</p>

            <p><strong>हीमोग्लोबिन के मुख्य कार्य:</strong></p>
            <ul>
                <li><strong>ऑक्सीजन परिवहन:</strong> फेफड़ों से ऑक्सीजन लेकर पूरे शरीर की कोशिकाओं तक पहुंचाना</li>
                <li><strong>कार्बन डाइऑक्साइड परिवहन:</strong> शरीर से CO2 को फेफड़ों तक वापस ले जाना</li>
                <li><strong>रक्त का pH संतुलन:</strong> रक्त की अम्लता और क्षारीयता को नियंत्रित करना</li>
                <li><strong>ऑक्सीजन संग्रहण:</strong> मांसपेशियों में ऑक्सीजन संग्रहित करना</li>
            </ul>

