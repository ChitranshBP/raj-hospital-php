            <h2>हीमोग्लोबिन की समस्याओं से बचाव (Prevention)</h2>

            <p><strong>हीमोग्लोबिन के स्तर</strong> को स्वस्थ रखने और समस्याओं से बचने के लिए कुछ उपाय अपनाएं:</p>

            <h3>1. संतुलित आहार लें</h3>
            <p>रोजाना <strong>आयरन, विटामिन B12, फोलिक एसिड, और विटामिन C</strong> युक्त खाद्य पदार्थ खाएं। एक स्वस्थ आहार चार्ट बनाएं जिसमें विभिन्न प्रकार के खाद्य पदार्थ शामिल हों।</p>

            <h3>2. नियमित जांच कराएं</h3>
            <p><strong>साल में एक बार</strong> पूर्ण रक्त गणना (CBC) जांच जरूर कराएं। अगर आपको पहले से ही कोई समस्या है, तो डॉक्टर की सलाह के अनुसार बार-बार जांच कराएं।</p>

            <h3>3. धूम्रपान छोड़ें</h3>
