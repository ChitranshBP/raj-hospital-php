            <h2>हीमोग्लोबिन की जांच (Diagnosis)</h2>

            <p>हीमोग्लोबिन की जांच के लिए कई <strong>blood tests</strong> किए जाते हैं:</p>

            <h3>1. CBC (Complete Blood Count)</h3>
            <p>यह सबसे महत्वपूर्ण जांच है जिसमें <strong>हीमोग्लोबिन स्तर, RBCs की संख्या, WBCs, और platelets</strong> की जांच होती है।</p>

            <h3>2. Serum Iron, TIBC, और Ferritin</h3>
            <p>यह <strong>आयरन की कमी एनीमिया</strong> की पुष्टि करने के लिए किया जाता है।</p>

            <h3>3. विटामिन B12 और Folate Test</h3>
            <p>यह जांचने के लिए कि क्या इन विटामिन्स की कमी है जो <a href="/neuropathy-treatment-in-ranchi.php" style="color: #c62828;">nerve damage और neurological समस्याओं</a> का कारण बन सकती है।</p>

            <h3>4. Peripheral Blood Smear</h3>
            <p>रक्त को माइक्रोस्कोप में देखकर <strong>RBCs के आकार, आकार, और स्थिति</strong> की जांच।</p>

            <h3>5. अन्य जांचें</h3>
            <p>अंतर्निहित कारण जानने के लिए <strong>किडनी फंक्शन टेस्ट, लिवर टेस्ट, और अल्ट्रासाउंड</strong> भी किए जा सकते हैं।</p>

