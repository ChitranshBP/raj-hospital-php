            <h2>दमा (Asthma) क्या है?</h2>

            <p><strong>दमा या Asthma</strong> एक पुरानी (chronic) श्वसन स्थिति है जिसमें <strong>श्वसन मार्ग (airways)</strong> में सूजन और संकुचन हो जाता है। इससे सांस लेने में कठिनाई होती है।</p>

            <p>दमा में श्वसन मार्ग अधिक संवेदनशील (sensitive) हो जाते हैं, जिससे कुछ <strong>ट्रिगर्स (triggers)</strong> के संपर्क में आने पर:</p>

            <ul>
                <li>श्वसन मार्ग में <strong>मांसपेशियों का संकुचन</strong> (muscle tightening)</li>
                <li>श्वसन मार्ग की <strong>भीतरी परत में सूजन</strong> (inflammation)</li>
                <li><strong>श्लेष्म (mucus)</strong> का अधिक निर्माण</li>
            </ul>

            <p>इन सबके कारण <strong>वायु प्रवाह</strong> में रुकावट आती है और <strong>सांस लेने में कठिनाई</strong> होती है।</p>

            <div class="highlight-box">
                <strong>महत्वपूर्ण:</strong> दमा एक <strong>incurable condition</strong> है, लेकिन सही इलाज और देखभाल से इसे नियंत्रित किया जा सकता है। अधिकतर दमा के मरीज <strong>सामान्य जीवन</strong> जी सकते हैं।
            </div>

            <!-- Section 2: Main Symptoms -->
            <h2>दमा के प्रमुख लक्षण (Asthma Symptoms)</h2>

            <p><strong>दमा के लक्षण</strong> हर व्यक्ति में अलग-अलग हो सकते हैं। कुछ लोगों को हल्के लक्षण होते हैं, जबकि कुछ को गंभीर लक्षण हो सकते हैं।</p>

            <div class="symptom-list">
                <div class="symptom-card">
                    <h4>1. सांस फूलना (Shortness of Breath)</h4>
                    <p>दमा का सबसे आम लक्षण। सांस फूलना विशेषकर रात को या व्यायाम के बाद अधिक होता है।</p>
                </div>
                <div class="symptom-card">
                    <h4>2. छाती में घरघराहट (Wheezing)</h4>
                    <p>सांस छोड़ते समय छाती से <strong>सीटी जैसी आवाज़ (whistling sound)</strong> आना। यह दमा का प्रमुख लक्षण है।</p>
                </div>
                <div class="symptom-card">
                    <h4>3. खांसी (Coughing)</h4>
                    <p>लगातार खांसी, विशेषकर <strong>रात को</strong> या सुबह जल्दी। यह खांसी सूखी या कफ युक्त हो सकती है।</p>
                </div>
                <div class="symptom-card">
                    <h4>4. छाती में भारीपन (Chest Tightness)</h4>
                    <p>छाती में <strong>जकड़न या दर्द</strong> महसूस होना, जैसे कि कोई भारी चीज छाती पर रखी हो।</p>
                </div>
            </div>

            <h3>दमा के अन्य लक्षण:</h3>
            <ul>
                <li><strong>सांस लेने में कठिनाई</strong> especially during physical activity</li>
                <li><strong>बात करने में कठिनाई</strong> - पूरा वाक्य न कह पाना</li>
                <li><strong>नींद में बाधा</strong> - रात को उठना खांसी या सांस फूलने से</li>
                <li><strong>थकान</strong> - श्वसन समस्याओं के कारण ऊर्जा की कमी</li>
                <li><strong>चिंता और घबराहट</strong> - सांस नहीं आने से</li>
            </ul>

            <div class="warning-box">
                <strong>नोट:</strong> कुछ लोगों को केवल <strong>खांसी</strong> हो सकती है, बिना सांस फूलने के। इसे <strong>Cough-Variant Asthma</strong> कहते हैं। अगर लगातार खांसी है, तो डॉक्टर से मिलना चाहिए।
            </div>

            <!-- Section 3: Types -->
            <h2>दमा के प्रकार (Types of Asthma)</h2>

            <p>दमा कई प्रकार का होता है। सही प्रकार जानना जरूरी है ताकि उचित इलाज किया जा सके।</p>

            <h3>1. एलर्जिक दमा (Allergic Asthma)</h3>
            <p>यह <strong>एलर्जी</strong> से जुड़ा होता है। <strong>धूल, परागकण, पालतू जानवरों की रूसी</strong> आदि एलर्जेंस के संपर्क में आने पर लक्षण बढ़ जाते हैं। यह दमा का सबसे आम प्रकार है।</p>

            <h3>2. गैर-एलर्जिक दमा (Non-Allergic Asthma)</h3>
            <p>यह एलर्जी से नहीं, बल्कि <strong>तनाव, व्यायाम, ठंडी हवा, या मौसम</strong> जैसे कारणों से होता है।</p>

            <h3>3. व्यायाम-प्रेरित दमा (Exercise-Induced Asthma)</h3>
            <p>कुछ लोगों को केवल <strong>व्यायाम</strong> के दौरान या उसके बाद सांस फूलता है। यह <strong>exercise-induced bronchoconstriction (EIB)</strong> भी कहलाता है।</p>

            <h3>4. व्यावसायिक दमा (Occupational Asthma)</h3>
            <p>कुछ कामों में <strong>रसायनों, धुएं, या धूल</strong> के संपर्क में आने से दमा हो सकता है।</p>

            <h3>5. बच्चों में दमा (Childhood Asthma)</h3>
            <p><strong>बच्चों में दमा</strong> बहुत आम है। यह अक्सर एलर्जी से जुड़ा होता है। कई बच्चों में यह <strong>बड़े होने पर ठीक</strong> हो जाता है, लेकिन कुछ में जीवन भर रहता है।</p>

            <!-- Section 4: Triggers -->
            <h2>दमा के कारण और ट्रिगर्स (Causes & Triggers)</h2>

            <p>दमा के <strong>सटीक कारण</strong> अभी तक पूरी तरह ज्ञात नहीं हैं, लेकिन कुछ कारक इसे बढ़ा सकते हैं:</p>

            <h3>आनुवंशिक (Genetic) कारक:</h3>
            <ul>
                <li>परिवार में <strong>दमा, एलर्जी, या एक्जिमा</strong> का इतिहास</li>
                <li>माता-पिता में से किसी एक को दमा होना</li>
            </ul>

            <h3>पर्यावरणीय (Environmental) कारक:</h3>
            <ul>
                <li><strong>धूल और धुआं</strong> - घर की धूल, वायु प्रदूषण</li>
                <li><strong>परागकण (Pollen)</strong> - फूलों और पेड़ों से</li>
                <li><strong>पालतू जानवरों की रूसी</strong> - कुत्ते, बिल्ली आदि</li>
                <li><strong>कवक कीट (Mold)</strong> - नम जगहों पर</li>
                <li><strong>ठंडी हवा</strong> - विशेषकर सुबह और रात</li>
                <li><strong>तनाव और भावनात्मक तनाव</strong></li>
            </ul>

            <h3>अन्य ट्रिगर्स:</h3>
            <ul>
                <li><strong>व्यायाम</strong> - especially in cold and dry air</li>
                <li><strong>संक्रमण</strong> - सर्दी, फ्लू, निमोनिया</li>
                <li><strong>दवाइयां</strong> - aspirin, ibuprofen, beta-blockers</li>
                <li><strong>खाद्य पदार्थ</strong> - कुछ लोगों को कुछ खाद्य से एलर्जी</li>
                <li><strong>महिलाओं में हार्मोनल परिवर्तन</strong> - मासिक धर्म, गर्भावस्था</li>
            </ul>

            <div class="highlight-box">
                <strong>जानकारी:</strong> हर दमा के मरीज के लिए <strong>ट्रिगर अलग</strong> हो सकते हैं। अपने ट्रिगर पहचानना और उनसे बचना दमा नियंत्रण का सबसे अच्छा तरीका है।
            </div>

            <!-- Section 5: Diagnosis -->
            <h2>दमा का निदान (Diagnosis)</h2>

            <p>दमा का <strong>सही निदान</strong> केवल डॉक्टर ही कर सकता है। इसके लिए कई tests किए जाते हैं:</p>

            <h3>1. स्पायरोमेट्री (Spirometry)</h3>
            <p>यह <strong>फेफड़ों की कार्यक्षमता</strong> जांचने की मुख्य test है। इसमें आप गहरी सांस खींचकर जितनी जल्दी हो सके उतनी हवा बाहर निकालते हैं। यह <strong>FEV1</strong> (Forced Expiratory Volume) को मापता है।</p>

            <h3>2. पीक फ्लो मीटर (Peak Flow Meter)</h3>
            <p>यह <strong>श्वास निकासी की गति</strong> (how fast you can exhale) मापता है। आप घर पर भी इसका उपयोग कर सकते हैं।</p>

            <h3>3. ब्रॉन्कियल प्रोवोकेशन टेस्ट</h3>
            <p>जब स्पायरोमेट्री सामान्य हो तो <strong>bronchial provocation test</strong> किया जाता है। इसमें श्वसन मार्ग को सिकोड़ने वाली दवा दी जाती है और प्रतिक्रिया देखी जाती है।</p>

            <h3>4. एलर्जी टेस्ट</h3>
            <p>यह जानने के लिए कि <strong>कौन से एलर्जेंस</strong> आपके दमा को ट्रिगर करते हैं। skin prick test या blood test किया जाता है।</p>

            <h3>5. छाती का X-ray</h3>
            <p>अन्य श्वसन समस्याओं को <strong>बाहर (exclude)</strong> करने के लिए।</p>

            <!-- Section 6: Treatment -->
            <h2>दमा का इलाज (Asthma Treatment)</h2>

            <p>दमा का इलाज दो मुख्य <strong>दवाइयों</strong> पर आधारित है:</p>

            <h3>1. रिलीवर दवाइयाँ (Reliever Medications)</h3>
            <p>ये <strong>जल्दी राहत</strong> देने वाली दवाइयाँ हैं जो दमा के दौरे के समय उपयोग की जाती हैं:</p>
            <ul>
                <li><strong>Short-Acting Beta Agonists (SABA)</strong> - जैसे Salbutamol</li>
                <li><strong>Anticholinergics</strong> - जैसे Ipratropium</li>
            </ul>
            <p>ये दवाइयाँ श्वसन मार्ग की <strong>मांसपेशियों को आराम</strong> देती हैं और तुरंत सांस लेने में आराम करती हैं।</p>

            <h3>2. कंट्रोलर दवाइयाँ (Controller Medications)</h3>
            <p>ये <strong>दीर्घकालिक</strong> दवाइयाँ हैं जो दमा को <strong>नियंत्रित</strong> रखती हैं:</p>
            <ul>
                <li><strong>Inhaled Corticosteroids (ICS)</strong> - जैसे Budesonide, Fluticasone</li>
                <li><strong>Long-Acting Beta Agonists (LABA)</strong> - जैसे Salmeterol</li>
                <li><strong>Leukotriene Receptor Antagonists</strong> - जैसे Montelukast</li>
                <li><strong>Theophylline</strong></li>
            </ul>

            <h3>3. इनहेलर का सही उपयोग</h3>
            <p><strong>इनहेलर (inhaler)</strong> दमा इलाज का सबसे अच्छा और आसान तरीका है। लेकिन इसे <strong>सही तरीके से</strong> उपयोग करना जरूरी है:</p>
            <ol>
                <li>इनहेलर को अच्छी तरह <strong>shake करें</strong></li>
                <li><strong>मुंह में</strong> मुखपत्र (mouthpiece) लगाएं</li>
                <li><strong>सांस बाहर निकालें</strong> (पूरी तरह)</li>
                <li>इनहेलर दबाएं और <strong>धीरे-धीरे गहरी सांस लें</strong></li>
                <li><strong>10 सेकंड</strong> तक सांस रोकें</li>
                <li>धीरे-धीरे <strong>सांस छोड़ें</strong></li>
            </ol>

            <div class="warning-box">
                <strong>महत्वपूर्ण:</strong> कई लोग इनहेलर का <strong>सही उपयोग नहीं</strong> करते। अगर आपको दमा है, तो अपने डॉक्टर से <strong>इनहेलर technique</strong> सीखना जरूरी है। गलत technique से दवा फेफड़ों तक नहीं पहुंचती।
            </div>

            <!-- Section 7: Prevention -->
            <h2>दमा से बचाव के उपाय (Asthma Prevention)</h2>

            <p>दमा को <strong>पूरी तरह ठीक</strong> नहीं किया जा सकता, लेकिन इसे <strong>नियंत्रित</strong> रखना और दौरों से बचना संभव है:</p>

            <h3>1. ट्रिगर्स से बचें</h3>
            <ul>
                <li><strong>धूल और धुएं</strong> से दूर रहें</li>
                <li><strong>एलर्जी</strong> के कारण जानें और उनसे बचें</li>
                <li><strong>ठंडी हवा</strong> में मुंह ढककर निकलें</li>
                <li><strong>धूम्रपान</strong> और <strong>पासिव स्मोकिंग</strong> से बचें</li>
            </ul>

            <h3>2. दवाइयाँ नियमित लें</h3>
            <p>अपनी <strong>controller medication</strong> नियमित रूप से लें, भले ही आपको लक्षण न हों। यह श्वसन मार्ग की <strong>सूजन को नियंत्रित</strong> रखती है।</p>

            <h3>3. स्वस्थ जीवनशैली अपनाएं</h3>
            <ul>
                <li><strong>नियमित व्यायाम</strong> करें (डॉक्टर की सलाह से)</li>
                <li><strong>स्वस्थ आहार</strong> लें - ताजे फल, सब्जियां</li>
                <li><strong>वजन</strong> को नियंत्रित रखें</li>
                <li><strong>पर्याप्त नींद</strong> लें</li>
            </ul>

            <h3>4. नियमित जांच कराएं</h3>
            <p>अपने <strong>डॉक्टर से नियमित</strong> मिलें और <strong>फेफड़ों की कार्यक्षमता</strong> जांचते रहें।</p>

            <h3>5. Asthma Action Plan बनाएं</h3>
            <p>अपने डॉक्टर के साथ मिलकर एक <strong>written action plan</strong> बनाएं जिसमें:</p>
            <ul>
                <li>दैनिक दवा की जानकारी</li>
                <li>लक्षण बिगड़ने पर क्या करना है</li>
                <li>Emergency कब जाना है</li>
                <li>Emergency contact numbers</li>
            </ul>

