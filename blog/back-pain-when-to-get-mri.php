                <h2 class="raj-h2"><i data-feather="message-circle" class="raj-h2-icon"></i> Frequently Asked Questions</h2>
                <div class="space-y-4">
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">When should back pain be investigated with an MRI?</h3>
                        <p class="text-gray-700">When there are red-flag features rather than simply because pain is severe: progressive leg or foot weakness, saddle numbness, new bladder or bowel difficulty, unexplained weight loss or fever, a cancer history, constant pain worse at night, pain after significant injury or in osteoporosis, and leg pain not improving after about six weeks of proper conservative treatment. Pain severity alone is a poor guide.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">How long should back pain last before I worry?</h3>
                        <p class="text-gray-700">Most simple episodes improve substantially within two to six weeks, and the majority settle without imaging or specialist input. Pain persisting beyond six weeks despite appropriate treatment, or progressively worsening rather than easing, deserves review. Any red-flag symptom needs assessment immediately regardless of duration.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What are the emergency red flags for back pain?</h3>
                        <p class="text-gray-700">Difficulty passing urine or loss of bladder or bowel control, numbness in the saddle area around the genitals and inner thighs, rapidly worsening weakness in both legs, or severe pain after a significant fall or accident. These can indicate cauda equina syndrome or an unstable spinal injury. Cauda equina is a surgical emergency where a delay of hours can cause permanent loss of bladder and sexual function.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What does an MRI show that an X-ray does not?</h3>
                        <p class="text-gray-700">An X-ray shows bone: fractures, alignment, bone spurs and narrowed disc spaces. It cannot show the structures that cause nerve symptoms. An MRI uses a magnetic field rather than radiation and shows soft tissue in detail, including the discs and whether one is herniated, the spinal cord and nerve roots and whether they are compressed, ligaments, muscles, and changes from infection or tumour.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Can an MRI show something that is not causing my pain?</h3>
                        <p class="text-gray-700">Yes, and this matters. Disc bulges, degenerative changes and mild herniations are frequently found in people with no back pain at all, and become more common with age. Treating a scan finding rather than the patient leads to unnecessary surgery. This is why doctors match imaging to the clinical examination, and why a scan without proper examination first can mislead more than it helps.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Is bed rest good for back pain?</h3>
                        <p class="text-gray-700">No. Prolonged bed rest was standard decades ago and has since been shown to slow recovery, because muscles weaken, joints stiffen and pain sensitivity rises. Rest a day or two at most if pain is severe, then return to gentle movement and normal activity as far as pain allows. Staying active within comfort is one of the best-evidenced treatments for simple back pain.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">What conservative treatments are tried before surgery?</h3>
                        <p class="text-gray-700">Staying active, structured physiotherapy for core strength and posture, simple analgesia with short anti-inflammatory courses where safe, heat or ice, weight management, workstation and lifting adjustments, and medication for nerve pain in selected cases. For persistent nerve root pain, an image-guided steroid injection can help. Most patients improve substantially and never need an operation.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">When is spine surgery the right conversation?</h3>
                        <p class="text-gray-700">Urgently for cauda equina, cord compression, spinal infection with deficit, unstable fracture, or a tumour compressing the cord. As a planned option when leg pain from confirmed nerve compression has not improved after six to twelve weeks of proper treatment, when weakness is progressive, or when canal narrowing severely limits walking. Surgery is far more reliable for nerve-compression leg pain than for back pain alone.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Is sciatica always caused by a slipped disc?</h3>
                        <p class="text-gray-700">No. A herniated disc pressing on a nerve root is the commonest cause, but sciatica-like leg pain can also come from spinal canal narrowing, facet joint arthritis, piriformis muscle irritation, or occasionally conditions outside the spine such as pelvic masses. Diabetic nerve damage can mimic it too. The pain pattern, neurological examination and imaging all need to agree before blaming a disc.</p>
                    </div>
