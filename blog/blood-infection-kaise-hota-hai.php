                <!-- Section 1: What is Blood Infection -->
                <h2 class="raj-h2">Blood Infection (Sepsis) Kya Hai?</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Sepsis</strong> एक life-threatening condition है जो तब होती है जब शरीर की immune system किसी infection के जवाब में खुद को ही damage करती है। सामान्य तौर पर, हमारी immune system एक infection को एक specific area में confine करती है। लेकिन sepsis में, यह infection और chemicals पूरे शरीर में फैल जाते हैं।
                </p>

                <p class="text-gray-700 mb-4">
                    Sepsis का सबसे severe form <strong>Septic Shock</strong> है, जिसमें <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">blood pressure</a> बहुत कम हो जाता है और organs को adequate blood supply नहीं मिलती। यह condition बिना तुरंत treatment के fatal हो सकती है।
                </p>

                <div class="raj-callout raj-callout-info">
                    <strong class="text-blue-700">महत्वपूर्ण आंकड़े:</strong>
                    <span class="text-gray-700"> WHO के अनुसार, हर साल दुनिया भर में लगभग 49 million लोग sepsis से प्रभावित होते हैं और लगभग 11 million लोग इससे मारे जाते हैं। India में यह एक major cause of mortality है।</span>
                </div>

                <!-- Section 2: How it Happens -->
                <h2 class="raj-h2">Sepsis Kaise Hota Hai? (How Does Sepsis Develop?)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Sepsis</strong> का development एक cascade process है। आइए समझें यह stepwise कैसे होता है:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Step 1: Infection Ka Entry</h4>
                        <p class="text-sm text-gray-600">Bacteria, viruses, fungi, या parasites शरीर में enter होते हैं। यह skin, lungs, urinary tract, gastrointestinal tract, या किसी और जगह से शुरू हो सकता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Step 2: Immune System Response</h4>
                        <p class="text-sm text-gray-600">शरीर की immune system infection से लड़ने के लिए cytokines और other chemicals release करती है। यह normal inflammatory response है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Step 3: Systemic Inflammation</h4>
                        <p class="text-sm text-gray-600">Normal cases में यह response controlled होता है, लेकिन कुछ cases में inflammatory chemicals पूरे bloodstream में release हो जाते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Step 4: Organ Damage</h4>
                        <p class="text-sm text-gray-600">यह widespread inflammation blood clots बनाता है और blood vessels में से blood leak होने लगता है। इससे organs को oxygen और nutrients की supply कम हो जाती है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Step 5: Septic Shock</h4>
                        <p class="text-sm text-gray-600">सबसे severe case में, <a href="/specialties/cardiology.php" class="text-red-600 hover:underline font-semibold">blood pressure</a> dangerous levels तक गिर जाता है, जिससे multiple organ failure हो सकती है और बिना treatment के death तक हो सकती है।</p>
                    </div>
                </div>

                <!-- Section 3: Causes -->
                <h2 class="raj-h2">Sepsis Ke Karan (Causes of Sepsis)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Sepsis</strong> कई different types of infections से शुरू हो सकता है। सबसे common causes हैं:
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Lung Infections (Pneumonia)</h4>
                        <p class="text-sm text-gray-600">Pneumonia या severe flu से भी sepsis हो सकता है। Lung infection के bacteria bloodstream में enter कर सकते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Urinary Tract Infections (<a href="/specialties/urology.php" class="text-red-600 hover:underline font-semibold">UTI</a>)</h4>
                        <p class="text-sm text-gray-600">Kidney infections, bladder infections से भी sepsis हो सकता है। यह especially <a href="/specialties/obstetrics-and-gynaecology.php" class="text-red-600 hover:underline font-semibold">pregnant</a> women और elderly में common है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Abdominal Infections</h4>
                        <p class="text-sm text-gray-600">Appendix, gallbladder, या intestine से infection फैलकर sepsis कर सकता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Skin Infections</h4>
                        <p class="text-sm text-gray-600">Cellulitis, wound infections, या surgical site infections से bacteria blood में enter कर सकते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">5. Post-Surgical Infections</h4>
                        <p class="text-sm text-gray-600">Surgery के बाद wound infection से भी sepsis हो सकता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">6. Catheter Infections</h4>
                        <p class="text-sm text-gray-600">IV lines, urinary catheters, या dialysis catheters से भी infection enter कर सकती है।</p>
                    </div>
                </div>

