                <h2 class="raj-h2">The 6 Causes of Sudden Low BP During a Heart Attack</h2>
                <p class="text-gray-700 mb-4">
                    The <a href="https://rajhospitals.com/find-a-doctor.php" class="text-secondary-600 hover:underline font-semibold">cardiology team at RAJ Hospital</a> identifies six mechanisms:
                </p>
                <ol class="list-decimal list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Pump failure</strong> — large anterior wall MI reduces ejection fraction below 30%, dropping cardiac output.</li>
                    <li><strong>Right ventricular infarction</strong> — a blocked right coronary artery impairs venous return, dropping preload and BP.</li>
                    <li><strong>Cardiac tamponade</strong> — fluid in the pericardial sac compresses the heart; treated with emergency pericardiocentesis.</li>
                    <li><strong>Papillary muscle rupture</strong> — a torn mitral valve structure causes acute severe mitral regurgitation and pulmonary oedema.</li>
                    <li><strong>Ventricular septal rupture</strong> — a hole forms in the septum, shunting blood from left to right ventricle.</li>
                    <li><strong>Bezold-Jarisch reflex</strong> — inferior MI triggers a vagal surge causing bradycardia and hypotension.</li>
                </ol>

                <h2 class="raj-h2">Chronic Low Blood Pressure — Should You Worry?</h2>
                <p class="text-gray-700 mb-4">
                    If your BP runs 90/60 mmHg consistently, feels fine, and is not causing symptoms, you are probably a constitutionally low-BP person — common in young women, athletes, and people with low BMI. In most studies, this <em>baseline hypotension</em> is associated with <em>lower</em>, not higher, long-term cardiovascular risk.
                </p>
                <p class="text-gray-700 mb-4">
                    However, the <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">internal medicine specialists at RAJ Hospital</a> recommend evaluation if chronic low BP is accompanied by:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li>Unexplained fainting or near-fainting</li>
                    <li>Fatigue that limits daily activity</li>
                    <li>Reduced exercise tolerance</li>
                    <li>Cold intolerance, weight gain, hair loss (thyroid)</li>
                    <li>Family history of valve disease or cardiomyopathy</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    The workup usually includes an ECG, 2D echo, thyroid panel, cortisol level, and a tilt-table test if autonomic dysfunction is suspected. RAJ Hospital's autonomic lab in Ranchi is one of the few in eastern India with formal tilt-table and Valsalva testing capability.
                </p>

                <h2 class="raj-h2">Managing Low BP at Home — Practical Tips</h2>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Hydrate well</strong> — 2.5–3 litres of water daily; add a pinch of salt in summer.</li>
                    <li><strong>Stand up slowly</strong> — pause at the edge of the bed for 30 seconds before walking.</li>
                    <li><strong>Avoid prolonged standing</strong> — flex calf muscles periodically.</li>
                    <li><strong>Compression stockings</strong> — class II (20–30 mmHg) for orthostatic hypotension.</li>
                    <li><strong>Small, frequent meals</strong> — large meals shunt blood to the gut and drop BP.</li>
                    <li><strong>Avoid excessive alcohol</strong> — it dilates blood vessels and worsens hypotension.</li>
                </ul>

