                <h2 class="raj-h2">Understanding Blood Pressure — The Basics</h2>
                <p class="text-gray-700 mb-4">
                    Blood pressure (BP) is the force that blood exerts on the walls of arteries. It is written as two numbers: <strong>systolic</strong> (pressure when the heart contracts) over <strong>diastolic</strong> (pressure when the heart relaxes). The current international classification is:
                </p>
                <ul class="list-disc list-inside space-y-2 text-gray-700 mb-6">
                    <li><strong>Normal</strong> — systolic &lt;120 AND diastolic &lt;80 mmHg</li>
                    <li><strong>Elevated</strong> — systolic 120–129 AND diastolic &lt;80</li>
                    <li><strong>High BP stage 1</strong> — 130–139 / 80–89</li>
                    <li><strong>High BP stage 2</strong> — ≥140 / ≥90</li>
                    <li><strong>Hypotension</strong> — &lt;90 / &lt;60 mmHg</li>
                    <li><strong>Cardiogenic shock</strong> — &lt;90 / &lt;60 with organ hypoperfusion</li>
                </ul>
                <p class="text-gray-700 mb-4">
                    Most heart-attack-prevention messaging focuses on <em>high</em> BP, but low BP matters too. A 2022 study in <em>The Lancet</em> analysing 1.3 million adults found a U-shaped relationship: both persistent hypertension above 140/90 and persistent hypotension below 90/60 carried higher cardiovascular mortality than the 110-120 / 70-80 range.
                </p>

                <h2 class="raj-h2">Why Sudden Low BP Often Means a Heart Attack Is Happening</h2>
                <p class="text-gray-700 mb-4">
                    When a coronary artery blocks, the part of the heart muscle downstream stops pumping effectively. The stroke volume drops, the cardiac output falls, and BP plummets. If the BP falls below the threshold that perfuses the brain and kidneys, the patient goes into <strong>cardiogenic shock</strong> — a state where the heart cannot pump enough blood to meet the body's needs.
                </p>
                <p class="text-gray-700 mb-4">
                    Cardiogenic shock occurs in 5–10% of acute heart attacks and carries a hospital mortality of 40–60%, even in the best centres. The <a href="https://rajhospitals.com/" class="text-secondary-600 hover:underline font-semibold">cardiologists at RAJ Hospital Ranchi</a> use a multi-pronged protocol: emergency revascularisation with primary PCI, intra-aortic balloon pump (IABP) or Impella support, inotropes, and mechanical circulatory support when needed. Door-to-support time is the single biggest determinant of survival.
                </p>

