                        <p class="text-sm text-gray-600">अचानक चक्कर आना, बेहोशी का feeling, या अत्यधिक थकान heart attack का warning हो सकता है। खासकर अगर यह बिना किसी reason के हो। महिलाओं में कई दिन पहले से अत्यधिक थकान महसूस हो सकती है।</p>
