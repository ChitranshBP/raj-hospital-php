                        <p class="text-sm text-gray-600">मतली, उल्टी, या indigestion जैसा feel करना heart attack का symptom हो सकता है। खासकर महिलाओं में यह symptom ज्यादा common है। कई लोग इसे stomach problem समझकर ignore कर देते हैं।</p>
