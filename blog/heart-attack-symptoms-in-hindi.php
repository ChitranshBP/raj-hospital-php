                        <h4 class="font-bold text-red-600 mb-2">4. ठंडा पसीना (Cold Sweating)</h4>
                        <p class="text-sm text-gray-600">अचानक ठंडा पसीना आना एक warning sign हो सकता है। यह stress या exertion के बिना भी हो सकता है। अगर आपको flush, cold sweat आए और मतली महसूस हो, तो तुरंत medical help लें।</p>
