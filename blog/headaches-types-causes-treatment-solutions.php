                <h2 class="text-xl font-bold text-gray-800 border-b-2 border-primary-600 pb-2 mt-8 mb-4">Headache ke Different Types (सिरदर्द के प्रकार)</h2>

                <p class="text-gray-700 mb-4">
                    Headaches ko mainly do categories mein divide kiya gaya hai: <strong>Primary Headaches</strong> (jo khud ki condition hain) aur <strong>Secondary Headaches</strong> (jo kisi aur problem se hoti hain). Aao details mein samjhein:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">1. Tension Headache (टेंशन हेडएक)</h4>
                        <p class="text-gray-700 mb-2">Ye sabse common headache type hai. Ismein mild to moderate pain dono sides of head mehsoos hota hai, jaise band tight ho. Stress, anxiety, poor posture, ya eye strain se hota hai.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Pressure-like pain, tenderness in scalp/neck, difficulty sleeping</p>
                        <p class="text-sm text-gray-600"><strong>Duration:</strong> 30 minutes se lekar 7 days tak</p>
                    </div>

                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">2. Migraine (माइग्रेन)</h4>
                        <p class="text-gray-700 mb-2">Migraine is a neurological condition jismein severe, throbbing pain usually ek side of head pe hoti hai. Ye kai baar nausea, vomiting, aur light/sound sensitivity ke saath hoti hai. For detailed information, read our <a href="<?php echo $base_url; ?>migraine-and-headaches-treatment-in-ranchi.php" class="text-primary-600 hover:underline font-semibold">migraine treatment guide</a>.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Throbbing pain, nausea/vomiting, aura (visual disturbances), sensitivity to light/sound/smell</p>
                        <p class="text-sm text-gray-600"><strong>Duration:</strong> 4 se 72 hours</p>
                    </div>

                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">3. Cluster Headache (क्लस्टर हेडएक)</h4>
                        <p class="text-gray-700 mb-2">Ye sabse painful headache type hai. Ye sudden start hota hai aur short duration ka hota hai (15 minutes se 3 hours). Pain usually ek eye ke around hota hai.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Excruciating pain around one eye, watery eye, nasal congestion, restlessness</p>
                        <p class="text-sm text-gray-600"><strong>Duration:</strong> 15 minutes se 3 hours, multiple times a day for weeks</p>
                    </div>

                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">4. Sinus Headache (साइनस हेडएक)</h4>
                        <p class="text-gray-700 mb-2">Sinus infection ya inflammation se hota hai. Forehead, cheeks, nose bridge pe pressure aur pain mehsoos hota hai. Cold ya allergies ke saath often hota hai.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Facial pressure/pain, nasal congestion, fever, green nasal discharge</p>
                        <p class="text-sm text-gray-600"><strong>Duration:</strong> Infection ke saath generally 7-10 days</p>
                    </div>

                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">5. Cervicogenic Headache (सर्वाइकोजेनिक हेडएक)</h4>
                        <p class="text-gray-700 mb-2">Ye neck ya spine ki problem se hoti hai. Cervical spine ki issues, poor posture, ya neck injury se trigger hoti hai. Neck pain aur shoulder pain ke saath hoti hai.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Pain starting from neck, radiating to head, limited neck movement, shoulder/arm pain</p>
                        <p class="text-sm text-gray-600"><strong>Treatment:</strong> <a href="<?php echo $base_url; ?>back-pain-and-sciatica-treatment-in-ranchi.php" class="text-primary-600 hover:underline font-semibold">Physical therapy aur spine treatment</a> help karta hai</p>
                    </div>

                    <div class="bg-gray-50 p-5 rounded-lg border-l-4 border-primary-600">
                        <h4 class="font-bold text-primary-600 text-lg mb-2">6. Rebound Headache (रिबाउंड हेडएक)</h4>
                        <p class="text-gray-700 mb-2">Overuse of pain medications se hota hai. Jab aap frequently headache medicines lete ho, toh body unpe dependent ho jati hai aur medicine band karne pe rebound headache hota hai.</p>
                        <p class="text-sm text-gray-600"><strong>Symptoms:</strong> Daily headaches, worse in morning, continuing despite medication</p>
                        <p class="text-sm text-gray-600"><strong>Prevention:</strong> Pain medicines 2-3 days/week se zyada na lein</p>
                    </div>
                </div>

