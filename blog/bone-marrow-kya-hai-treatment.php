                <!-- Section 3: Diseases -->
                <h2 class="raj-h2">Bone Marrow Se Related Diseases</h2>

                <p class="text-gray-700 mb-4">
                    जब bone marrow सही से काम नहीं करता, तो कई serious diseases हो सकती हैं:
                </p>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Leukemia (Blood Cancer)</h4>
                        <p class="text-sm text-gray-600">White blood cells का cancer जिसमें bone marrow abnormal WBCs produce करता है। Types: ALL, AML, CML, CLL.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Lymphoma</h4>
                        <p class="text-sm text-gray-600">Lymphatic system का cancer जो bone marrow को भी affect करता है। Hodgkin और Non-Hodgkin lymphoma।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Multiple Myeloma</h4>
                        <p class="text-sm text-gray-600">Plasma cells का cancer जो bones में lesions और bone marrow dysfunction करता है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Aplastic Anemia</h4>
                        <p class="text-sm text-gray-600">Bone marrow जब stem cells को damage हो जाते हैं और नई blood cells नहीं बना पाते।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">5. Sickle Cell Disease</h4>
                        <p class="text-sm text-gray-600">Genetic condition जिसमें RBCs abnormal sickle shape में बनते हैं और oxygen delivery affected होती है।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">6. Thalassemia</h4>
                        <p class="text-sm text-gray-600">Genetic blood disorder जिसमें hemoglobin production affected होता है।</p>
                    </div>
                </div>

                <!-- Section 4: Bone Marrow Transplant -->
                <h2 class="raj-h2">Bone Marrow Transplant (Stem Cell Transplant)</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Bone marrow transplant</strong> एक procedure है जिसमें diseased या damaged bone marrow को healthy stem cells से replace किया जाता है। यह एक potentially curative treatment है जो कई life-threatening conditions को cure कर सकता है।
                </p>

                <h3 class="text-lg font-bold text-gray-800 mt-6 mb-3">Types of Bone Marrow Transplant</h3>

                <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">1. Autologous Transplant</h4>
                        <p class="text-sm text-gray-600">Patient ke own stem cells use किए जाते हैं। सबसे पहले healthy stem cells collect किए जाते हैं, फिर high-dose chemotherapy दी जाती है, और फिर stem cells return किए जाते हैं। Less risk of rejection.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">2. Allogeneic Transplant</h4>
                        <p class="text-sm text-gray-600">Another person (donor) से stem cells लिए जाते हैं। Donor可以是 family member, unrelated matched donor, या umbilical cord blood। Higher risk but potentially curative for many diseases.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">3. Syngeneic Transplant</h4>
                        <p class="text-sm text-gray-600">Identical twin से stem cells लिए जाते हैं। Perfect match होने से complications कम होते हैं।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">4. Haploidentical Transplant</h4>
                        <p class="text-sm text-gray-600">Half-matched family member से transplant। नई technique जो more donors available करती है।</p>
                    </div>
                </div>

                <!-- Section 5: Process -->
                <h2 class="raj-h2">Bone Marrow Transplant Ka Process</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Bone marrow transplant process</strong> कई stages में complete होता है:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Stage 1: Evaluation और Matching</h4>
                        <p class="text-sm text-gray-600">Complete medical evaluation, HLA typing (tissue matching), donor search (if allogeneic), और psychological assessment। At RAJ Hospital, हमारी team patient aur family ko guide करती hai।</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Stage 2: Stem Cell Collection</h4>
                        <p class="text-sm text-gray-600">For autologous: Stem cells from blood (apheresis) collect किए जाते हैं through a machine that separates them from blood। For allogeneic: From donor through peripheral blood stem cell harvest या bone marrow harvest from hip bone।</p>
                    </div>
