                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">How long does it take to reduce hair fall naturally?</h3>
                        <p class="text-gray-700">Most people notice less hair fall within six to twelve weeks of consistent changes. Visible new growth usually takes three to six months, because hair grows only about one centimetre a month.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">Can drinking more water reduce hair fall?</h3>
                        <p class="text-gray-700">Staying hydrated supports overall health, but there is no strong evidence that drinking extra water reduces hair fall on its own. Focus on a balanced diet, enough protein, and treating the underlying cause.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border border-gray-100">
                        <h3 class="font-bold text-gray-800 mb-2">When should I consider a hair transplant?</h3>
                        <p class="text-gray-700">Consider a hair transplant when you have permanent thinning or bald areas, usually from pattern hair loss, that do not respond to medicines. A specialist will assess whether your hair loss is stable and whether your donor area is strong enough.</p>
