                        <h4 class="font-bold text-secondary-600">Stage 4: Gradual Replacement</h4>
                        <p class="text-sm text-gray-600">As new tissue forms, the hydrogel is gradually absorbed and replaced by the body's own bone and cartilage, eventually leaving only natural tissue.</p>
                    </div>
                </div>

