                <h2 class="raj-h2">Bone Hydrogel Kaise Kaam Karta Hai?</h2>

                <p class="text-gray-700 mb-4">
                    <strong>Bone hydrogel treatment</strong> की mechanism कई stages में काम करती है:
                </p>

                <div class="space-y-4 mb-6">
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Stage 1: Injection</h4>
                        <p class="text-sm text-gray-600">Under local anesthesia, the hydrogel is precisely injected into the damaged area using imaging guidance (X-ray or ultrasound) for accuracy.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Stage 2: Filling and Adhesion</h4>
                        <p class="text-sm text-gray-600">The hydrogel conforms to the shape of the defect and adheres to surrounding healthy tissue, creating a scaffold for new tissue growth.</p>
                    </div>
                    <div class="bg-gray-50 p-4 rounded-lg border-l-4 border-secondary-600">
                        <h4 class="font-bold text-secondary-600">Stage 3: Stimulating Healing</h4>
